#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import {
  appendFileSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { fileURLToPath } from "node:url";
import os from "node:os";
import path from "node:path";

import { flowIdsAndAreas, readFlowSpecTexts } from "./flow-ids.mjs";

const E2E_DIR = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
// Local reading copy only; gitignored. CI renders it into the job summary.
const CATALOG = path.join(E2E_DIR, "FLOWS.md");
const REQUIRED = ["id", "area", "userGoal", "steps"];

export function extractFlows(entries) {
  const flowTests = entries.filter((e) => e.tags.includes("@flow"));
  if (!flowTests.length)
    throw new Error("no @flow tests found — the catalog cannot be empty");
  const flows = flowTests.map((e) => {
    const ann = e.annotations.find((a) => a.type === "flow");
    if (!ann)
      throw new Error(
        `missing flow annotation on "${e.title}" (${e.location})`,
      );
    const meta = JSON.parse(ann.description);
    const text = (value) =>
      typeof value === "string" && value.trim().length > 0;
    const textList = (value) =>
      Array.isArray(value) && value.length > 0 && value.every(text);
    for (const key of REQUIRED) {
      const valid = key === "steps" ? textList(meta?.[key]) : text(meta?.[key]);
      if (!valid) {
        throw new Error(
          `flow "${e.title}": annotation missing ${key} or invalid value`,
        );
      }
    }
    for (const key of ["backendChecks", "browserChecks"]) {
      if (
        meta[key] !== undefined &&
        (!Array.isArray(meta[key]) || !meta[key].every(text))
      )
        throw new Error(`flow "${e.title}": annotation invalid ${key}`);
    }
    if (!textList(meta.backendChecks) && !textList(meta.browserChecks))
      throw new Error(`flow "${e.title}": annotation missing checks`);
    return {
      ...meta,
      title: e.title,
      location: e.location,
      tags: e.tags.filter((t) => t !== "@flow"),
    };
  });
  const seen = new Set();
  for (const f of flows) {
    if (seen.has(f.id)) throw new Error(`duplicate flow id ${f.id}`);
    seen.add(f.id);
  }
  return flows.sort((a, b) => a.id.localeCompare(b.id));
}

// [label, values] pairs where the Playwright-listed flows and the spec-text
// reading (flow-ids.mjs) disagree; empty when they match.
export function catalogDisagreements(flows, fromText) {
  const listedIds = [...new Set(flows.map((f) => f.id))].sort();
  const listedAreas = [...new Set(flows.map((f) => f.area))].sort();
  const missing = (a, b) => a.filter((x) => !b.includes(x));
  return [
    [
      "flow ids Playwright lists but spec text lacks",
      missing(listedIds, fromText.ids),
    ],
    [
      "flow ids in spec text that Playwright does not list",
      missing(fromText.ids, listedIds),
    ],
    [
      "areas Playwright lists but spec text lacks",
      missing(listedAreas, fromText.areas),
    ],
    [
      "areas in spec text that Playwright does not list",
      missing(fromText.areas, listedAreas),
    ],
  ].filter(([, values]) => values.length);
}

export function renderCatalog(flows) {
  const byArea = Map.groupBy(flows, (f) => f.area);
  const lines = [
    "# E2E Flow Catalog",
    "",
    "<!-- GENERATED by `yarn catalog` from the flow annotations in e2e/flows. Not committed. -->",
    "",
  ];
  for (const [area, group] of [...byArea.entries()].sort()) {
    lines.push(`## ${area}`, "");
    for (const f of group) {
      lines.push(
        `### ${f.id} — ${f.title.replace(`${f.id}: `, "")}`,
        "",
        `**Goal:** ${f.userGoal}`,
        "",
        `**Spec:** \`${f.location}\``,
        "",
        `**Tags:** ${f.tags.join(" ") || "—"}`,
        "",
        // The blank line before each list keeps the output prettier-clean, so
        // the pre-commit formatter cannot rewrite this file and break --check.
        "**User steps:**",
        "",
        ...f.steps.map((s, i) => `${i + 1}. ${s}`),
        "",
      );
      if (f.backendChecks?.length)
        lines.push(
          "**Backend state verified:**",
          "",
          ...f.backendChecks.map((c) => `- ${c}`),
          "",
        );
      if (f.browserChecks?.length)
        lines.push(
          "**Browser observations:**",
          "",
          ...f.browserChecks.map((c) => `- ${c}`),
          "",
        );
    }
  }
  return lines.join("\n");
}

export function collectFlowEntries(run = execFileSync) {
  const directory = mkdtempSync(path.join(os.tmpdir(), "flow-list-"));
  const listFile = path.join(directory, "entries.json");
  try {
    // The catalog documents which flows exist, independent of what a given run
    // executes — quarantining, live-LLM-gating or stack-gating a flow must not drop it from the catalog.
    run(
      "npx",
      [
        "playwright",
        "test",
        "--list",
        "--reporter=./scripts/flow-list-reporter.mjs",
      ],
      {
        cwd: E2E_DIR,
        encoding: "utf8",
        stdio: ["ignore", "ignore", "pipe"],
        env: {
          ...process.env,
          FLOW_CATALOG_OUT: listFile,
          E2E_INCLUDE_QUARANTINED: "1",
          E2E_LIVE_LLM: "1",
          E2E_INCLUDE_ERROR_FEED_STACK: "1",
          // The ordinary legs run with SKILLS_COHORT=ordinary, which narrows the
          // suite to what the Skills cohorts do not own (playwright.config.ts).
          SKILLS_COHORT: undefined,
        },
      },
    );
    // onBegin may write a partial list even when another spec failed collection.
    // A file is not proof of successful discovery: every nonzero exit must fail.
    return JSON.parse(readFileSync(listFile, "utf8"));
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

function main() {
  let flows;
  try {
    flows = extractFlows(collectFlowEntries());
  } catch (err) {
    console.error(err.stderr || err.message);
    process.exit(1);
  }
  const rendered = renderCatalog(flows);
  if (process.argv.includes("--check")) {
    // FLOWS.md is not committed: every PR that added or moved a flow rewrote
    // it, so two flow PRs always conflicted. The check validates the
    // annotations above and that the spec-text reading e2e-coverage uses
    // agrees with what Playwright lists.
    const problems = catalogDisagreements(
      flows,
      flowIdsAndAreas(readFlowSpecTexts(E2E_DIR)),
    );
    if (problems.length) {
      console.error(
        [
          "Flow ids and areas read from spec text disagree with Playwright.",
          "Write each flow id as a quoted string literal and its area as an `area:` literal.",
          ...problems.map(
            ([label, values]) => `  ${label}: ${values.join(", ")}`,
          ),
        ].join("\n"),
      );
      process.exit(1);
    }
    if (process.env.GITHUB_STEP_SUMMARY)
      appendFileSync(process.env.GITHUB_STEP_SUMMARY, `${rendered}\n`);
    console.log(
      `Flow catalog is valid: ${flows.length} flows in ${new Set(flows.map((f) => f.area)).size} areas.`,
    );
  } else {
    writeFileSync(CATALOG, rendered);
    console.log(`wrote ${CATALOG}`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
