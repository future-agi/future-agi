#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import os from "node:os";
import path from "node:path";

const E2E_DIR = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const CATALOG = path.join(E2E_DIR, "FLOWS.md");
const REQUIRED = ["id", "area", "userGoal", "steps"];

export function extractFlows(entries) {
  const flowTests = entries.filter((e) => e.tags.includes("@flow"));
  if (!flowTests.length)
    throw new Error("no @flow tests found — the catalog cannot be empty");
  const flows = flowTests.map((e) => {
    const ann = e.annotations.find((a) => a.type === "flow");
    if (!ann)
      throw new Error(
        `missing flow annotation on "${e.title}" (${e.location})`,
      );
    const meta = JSON.parse(ann.description);
    const text = (value) =>
      typeof value === "string" && value.trim().length > 0;
    const textList = (value) =>
      Array.isArray(value) && value.length > 0 && value.every(text);
    for (const key of REQUIRED) {
      const valid = key === "steps" ? textList(meta?.[key]) : text(meta?.[key]);
      if (!valid) {
        throw new Error(
          `flow "${e.title}": annotation missing ${key} or invalid value`,
        );
      }
    }
    for (const key of ["backendChecks", "browserChecks"]) {
      if (
        meta[key] !== undefined &&
        (!Array.isArray(meta[key]) || !meta[key].every(text))
      )
        throw new Error(`flow "${e.title}": annotation invalid ${key}`);
    }
    if (!textList(meta.backendChecks) && !textList(meta.browserChecks))
      throw new Error(`flow "${e.title}": annotation missing checks`);
    return {
      ...meta,
      title: e.title,
      location: e.location,
      tags: e.tags.filter((t) => t !== "@flow"),
    };
  });
  const seen = new Set();
  for (const f of flows) {
    if (seen.has(f.id)) throw new Error(`duplicate flow id ${f.id}`);
    seen.add(f.id);
  }
  return flows.sort((a, b) => a.id.localeCompare(b.id));
}

export function renderCatalog(flows) {
  const byArea = Map.groupBy(flows, (f) => f.area);
  const lines = [
    "# E2E Flow Catalog",
    "",
    "<!-- GENERATED by `yarn catalog` — do not edit. CI runs `yarn catalog:check`. -->",
    "",
  ];
  for (const [area, group] of [...byArea.entries()].sort()) {
    lines.push(`## ${area}`, "");
    for (const f of group) {
      lines.push(
        `### ${f.id} — ${f.title.replace(`${f.id}: `, "")}`,
        "",
        `**Goal:** ${f.userGoal}`,
        "",
        `**Spec:** \`${f.location}\``,
        "",
        `**Tags:** ${f.tags.join(" ") || "—"}`,
        "",
        // The blank line before each list keeps the output prettier-clean, so
        // the pre-commit formatter cannot rewrite this file and break --check.
        "**User steps:**",
        "",
        ...f.steps.map((s, i) => `${i + 1}. ${s}`),
        "",
      );
      if (f.backendChecks?.length)
        lines.push(
          "**Backend state verified:**",
          "",
          ...f.backendChecks.map((c) => `- ${c}`),
          "",
        );
      if (f.browserChecks?.length)
        lines.push(
          "**Browser observations:**",
          "",
          ...f.browserChecks.map((c) => `- ${c}`),
          "",
        );
    }
  }
  return lines.join("\n");
}

export function collectFlowEntries(run = execFileSync) {
  const directory = mkdtempSync(path.join(os.tmpdir(), "flow-list-"));
  const listFile = path.join(directory, "entries.json");
  try {
    // The catalog documents which flows exist, independent of what a given run
    // executes — quarantining or live-LLM-gating a flow must not delete it from FLOWS.md.
    run(
      "npx",
      [
        "playwright",
        "test",
        "--list",
        "--reporter=./scripts/flow-list-reporter.mjs",
      ],
      {
        cwd: E2E_DIR,
        encoding: "utf8",
        stdio: ["ignore", "ignore", "pipe"],
        env: {
          ...process.env,
          FLOW_CATALOG_OUT: listFile,
          E2E_INCLUDE_QUARANTINED: "1",
          E2E_LIVE_LLM: "1",
        },
      },
    );
    // onBegin may write a partial list even when another spec failed collection.
    // A file is not proof of successful discovery: every nonzero exit must fail.
    return JSON.parse(readFileSync(listFile, "utf8"));
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

function main() {
  let rendered;
  try {
    rendered = renderCatalog(extractFlows(collectFlowEntries()));
  } catch (err) {
    console.error(err.stderr || err.message);
    process.exit(1);
  }
  if (process.argv.includes("--check")) {
    const committed = readFileSync(CATALOG, "utf8");
    if (committed !== rendered) {
      console.error(
        "FLOWS.md is stale — run `yarn catalog` and commit the result.",
      );
      process.exit(1);
    }
    console.log("FLOWS.md is current.");
  } else {
    writeFileSync(CATALOG, rendered);
    console.log(`wrote ${CATALOG}`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
