test('H-NATIVE-OTLP child-first split and replay preserve immutable source IDs, timestamps and parents', async () => {
  const fixture = syntheticCopilotDetailsFixture({ projectName: cfg.projectName });
  const before = JSON.stringify(fixture);
  const members = spans(fixture);
  const parent = selectOtlpSpans(fixture, [{ traceId, spanId: root }]);
  const children = selectOtlpSpans(fixture, members.slice(1).map(s => ({ traceId: s.traceId, spanId: s.spanId })));
  const { req, calls } = recorder();
  const childReceipt = await sendOtlpExport(req, cfg, children);
  const parentReceipt = await sendOtlpExport(req, cfg, parent);
  expect(await sendOtlpExport(req, cfg, children)).toEqual(childReceipt);
  expect(calls[2].wire).toBe(calls[0].wire);
  expect(spans(JSON.parse(calls[0].wire))).toEqual(members.slice(1));
  expect(spans(JSON.parse(calls[1].wire))).toEqual([members[0]]);
  expect(childReceipt.spans.map(s => [s.traceId, s.spanId, s.parentSpanId])).toEqual(members.slice(1)
    .map(s => ['01234567-89ab-cdef-0123-456789abcdef', s.spanId, root]));
  expect(parentReceipt.spans.map(s => [s.spanId, s.parentSpanId])).toEqual([[root, undefined]]);
  expect(JSON.stringify(fixture)).toBe(before);
  expect(() => { spans(parent)[0].name = 'mutated'; }).toThrow(TypeError);
  const detached = structuredClone(fixture);
  const frozen = createOtlpFixture(detached);
  spans(detached)[0].name = 'caller changed';
  expect(spans(frozen)[0].name).toBe('invoke_agent');
});

test('H-NATIVE-OTLP receipt identities select the identical immutable export for replay', async () => {
  const fixture = syntheticCopilotFixture({ projectName: cfg.projectName });
  const { req, calls } = recorder();
  const receipt = await sendOtlpExport(req, cfg, fixture);
  const identities = receipt.spans.map(({ traceId, spanId }) => ({ traceId, spanId }));
  expect(identities[0]).toEqual({ traceId: '01234567-89ab-cdef-0123-456789abcdef', spanId: root });
  const replay = selectOtlpSpans(fixture, identities);
  expect(replay).toEqual(fixture);
  expect(await sendOtlpExport(req, cfg, replay)).toEqual(receipt);
  expect(calls[1].wire).toBe(calls[0].wire);
  expect(() => selectOtlpSpans(fixture, [identities[0], { traceId, spanId: root }])).toThrow(/unique/);
});

