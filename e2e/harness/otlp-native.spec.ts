test('H-NATIVE-OTLP accepts clean success, rejects malformed receipts and never reflects response text', async () => {
  for (const body of ['', '{}', '{"partialSuccess":{}}', '{"partialSuccess":{"rejectedSpans":"0","errorMessage":""}}',
    '{"partial_success":{"rejected_spans":0,"error_message":""}}']) {
    expect(() => assertOtlpSuccess(body)).not.toThrow();
  }
  for (const body of ['not-json', 'null', '[]', '{"partialSuccess":null}', '{"partialSuccess":[]}',
    '{"partialSuccess":{"rejectedSpans":-1}}', '{"partialSuccess":{"rejectedSpans":0.5}}',
    '{"partialSuccess":{"rejectedSpans":9007199254740992}}', '{"partialSuccess":{"rejectedSpans":"9223372036854775808"}}',
    '{"partialSuccess":{"rejectedSpans":true}}', '{"partialSuccess":{"rejectedSpans":"no"}}',
    '{"partialSuccess":{"errorMessage":5}}', '{"partialSuccess":{"rejectedSpan":"1"}}', '{"error":"synthetic"}']) {
    expect(() => assertOtlpSuccess(body)).toThrow();
  }
  const { req } = recorder('synthetic-response-content-not-for-logs', 500);
  await expect(sendTrace(req, legacy)).rejects.toThrow(/^collector HTTP 500$/);
});

