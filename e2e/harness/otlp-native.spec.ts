// H-NATIVE-OTLP: pure harness contract tests. No actor, browser, managed stack,
// vendor session, Python route, protobuf or gRPC qualification is implied.
const traceId = '0123456789abcdef0123456789abcdef'; // collector synthetic fixture
const otherTraceId = '11111111111141118111111111111111';
const thirdTraceId = '22222222222242228222222222222222';
const root = '0000000000000001', child = '0000000000000002';
const cfg = { collectorUrl: 'http://localhost:0', apiKey: 'unused', secretKey: 'unused', projectName: 'synthetic-native' };
const legacy: SendTraceConfig = { ...cfg, traceId, rootSpanId: root, childSpanId: child,
  startTimeUnixNano: '1000000', endTimeUnixNano: '2000000' };
const spans = (fixture: OtlpExport) => fixture.resourceSpans.flatMap(r => r.scopeSpans.flatMap(s => s.spans));
function recorder(body = '{}', status = 200) {
  const calls: { url: string; wire: string }[] = [];
  const req = { post: async (url: string, options: { data: unknown }) => {
    // Deliberately never retain or print authentication/header values.
    calls.push({ url, wire: options.data as string });
    return { status: () => status, text: async () => body, headers: () => ({}), dispose: async () => {} };
  } } as unknown as APIRequestContext;
  return { req, calls };
}

test('H-NATIVE-OTLP original two-span serialized wire remains byte-for-byte unchanged', async () => {
  const { req, calls } = recorder();
  const seeded = await sendTrace(req, legacy);
  // Independent literal, not generated by the code under test. Object key order
  // also pins the original JSON serialization; undefined parent is omitted.
  const expected = '{"resourceSpans":[{"resource":{"attributes":[{"key":"project_name","value":{"stringValue":"synthetic-native"}},{"key":"service.name","value":{"stringValue":"synthetic-native"}}]},"scopeSpans":[{"scope":{"name":"e2e-harness"},"spans":[{"traceId":"0123456789abcdef0123456789abcdef","spanId":"0000000000000001","name":"e2e.root","kind":1,"startTimeUnixNano":"1000000","endTimeUnixNano":"2000000","attributes":[],"status":{"code":1}},{"traceId":"0123456789abcdef0123456789abcdef","spanId":"0000000000000002","parentSpanId":"0000000000000001","name":"e2e.llm-call","kind":1,"startTimeUnixNano":"1000000","endTimeUnixNano":"2000000","attributes":[{"key":"fi.span.kind","value":{"stringValue":"llm"}}],"status":{"code":1}}]}]}]}';
  expect(calls).toEqual([{ url: 'http://localhost:0/v1/traces', wire: expected }]);
  expect(seeded).toEqual({ traceId: '01234567-89ab-cdef-0123-456789abcdef', spanIds: [root, child], projectName: cfg.projectName });
  await sendTrace(req, { ...legacy, additionalSpans: [] });
  expect(calls[1].wire).toBe(expected);
});

test('H-NATIVE-OTLP scope, per-span status and typed details extend sendTrace without replacing additionalSpans', async () => {
  const { req, calls } = recorder();
  const details = spans(syntheticCopilotDetailsFixture({ projectName: cfg.projectName }))[0];
  await sendTrace(req, { ...legacy, scope: { name: 'github.copilot', version: '1.0.98' },
    rootStatus: { code: 0 }, childStatus: details.status, childEvents: details.events, childLinks: details.links,
    additionalSpans: [{ spanId: '0000000000000003', parentSpanId: child, name: 'nested', status: { code: 1 },
      attributes: { nested: [false, 0, { text: '001' }] }, events: [], links: [] }] });
  const scope = JSON.parse(calls[0].wire).resourceSpans[0].scopeSpans[0];
  expect(scope.scope).toEqual({ name: 'github.copilot', version: '1.0.98' });
  expect(scope.spans.map((s: OtlpSpan) => s.status)).toEqual([{ code: 0 }, { code: 2, message: 'synthetic timeout' }, { code: 1 }]);
  expect(scope.spans[0]).not.toHaveProperty('events');
  expect(scope.spans[0]).not.toHaveProperty('links');
  expect(scope.spans[1].events).toEqual([{ name: 'exception', timeUnixNano: '1792024600000000000',
    attributes: [{ key: 'exception.type', value: { stringValue: 'Timeout' } }], droppedAttributesCount: 0 }]);
  expect(scope.spans[1].links).toEqual([{ traceId, spanId: child,
    attributes: [{ key: 'fi.agent.caused_by.work_id', value: { stringValue: 'synthetic-work' } }],
    droppedAttributesCount: 0, flags: 1 }]);
  expect(scope.spans[2].parentSpanId).toBe(child);
  expect(scope.spans[2].attributes).toEqual([{ key: 'nested', value: { arrayValue: { values: [
    { boolValue: false }, { doubleValue: 0 }, { kvlistValue: { values: [{ key: 'text', value: { stringValue: '001' } }] } },
  ] } } }]);
});

