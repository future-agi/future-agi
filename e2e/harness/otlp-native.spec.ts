test('H-NATIVE-OTLP mixed resources/scopes retain exact identities and selection uses trace plus span', async () => {
  const mixed = syntheticMixedFixture({ projectName: cfg.projectName, traceId,
    unknownTraceId: otherTraceId, siblingTraceId: thirdTraceId, siblingProjectName: 'synthetic-sibling' });
  const { req, calls } = recorder();
  const receipt = await sendOtlpExport(req, cfg, mixed);
  expect(JSON.parse(calls[0].wire)).toEqual(mixed);
  expect(receipt.spans.map(s => [s.traceId, s.spanId, s.projectName, s.resourceIndex, s.scopeIndex, s.scope])).toEqual(
    [
      ['01234567-89ab-cdef-0123-456789abcdef', cfg.projectName, 0, 0, { name: 'github.copilot', version: '1.0.98' }],
      ['11111111-1111-4111-8111-111111111111', cfg.projectName, 0, 1, { name: 'unrelated-sdk', version: 'synthetic-unknown' }],
      ['22222222-2222-4222-8222-222222222222', 'synthetic-sibling', 1, 0, { name: 'github.copilot', version: '1.0.98' }],
    ].flatMap(([tid, project, resourceIndex, scopeIndex, scope]) => [1, 2, 3, 4, 5]
      .map(i => [tid, String(i).padStart(16, '0'), project, resourceIndex, scopeIndex, scope])));
  const selection = selectOtlpSpans(mixed, [{ traceId: thirdTraceId, spanId: child }, { traceId, spanId: root }]);
  expect(spans(selection).map(s => [s.traceId, s.spanId])).toEqual([[traceId, root], [thirdTraceId, child]]);
  expect(selection.resourceSpans.map(r => r.scopeSpans.length)).toEqual([1, 1]);
  // Split one trace over scopes without changing ancestry or requiring a root
  // in every scope group. The parent may arrive in another HTTP delivery too.
  const original = mixed.resourceSpans[0].scopeSpans[0];
  const crossScope = createOtlpFixture({ resourceSpans: [{ resource: mixed.resourceSpans[0].resource,
    scopeSpans: [{ ...original, spans: original.spans.slice(0, 1) },
      { scope: { name: 'unrelated-sdk' }, spans: original.spans.slice(1) }] }] });
  await sendOtlpExport(req, cfg, crossScope);
  expect(JSON.parse(calls[1].wire)).toEqual(crossScope);
});

