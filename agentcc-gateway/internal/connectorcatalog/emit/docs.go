// docs writes the docs cards: docs/index.md, docs/apps/<app-id>.md and
// docs/platforms/<platform-id>.md. A card states the catalog's facts only
// (kind, tier, the vendor's own status label, a vendor approval still
// pending) and cites the record's sources; text from the data is escaped,
// so it renders as text.
func docs(cat *manifest.Catalog, meta Meta) (Files, error) {
	files := Files{"docs/index.md": []byte(docsIndex(cat, meta))}
	for _, a := range cat.Apps {
		files["docs/apps/"+a.ID+".md"] = []byte(appCard(a, meta))
	}
	for _, pl := range cat.Platforms {
		files["docs/platforms/"+pl.ID+".md"] = []byte(platformCard(pl, meta))
	}
	return files, nil
}

func generatedLine(meta Meta) string {
	return fmt.Sprintf("Generated by agentcc-catalog from catalog version %s (sha256 `%s`); do not edit.\n", meta.Version, meta.SHA256)
}

func docsIndex(cat *manifest.Catalog, meta Meta) string {
	var b strings.Builder
	b.WriteString("# Connector catalog\n\n")
	b.WriteString(generatedLine(meta))
	fmt.Fprintf(&b, "\nThe catalog holds %s and %s.\n", count(len(cat.Apps), "app"), count(len(cat.Platforms), "partner platform"))
	if len(cat.Apps) > 0 {
		b.WriteString("\n## Apps\n\n| App | What it does | Providers |\n| --- | --- | --- |\n")
		for _, a := range cat.Apps {
			var providers []string
			for _, p := range a.ProviderOrder() {
				label := fmt.Sprintf("%s: %s, %s", p.ID, p.Kind, p.Quality.Tier)
				if p.ID == a.DefaultProvider {
					label += ", default"
				}
				providers = append(providers, mdText(label))
			}
			fmt.Fprintf(&b, "| [%s](apps/%s.md) | %s | %s |\n", mdText(a.Name), a.ID, mdText(a.Description), strings.Join(providers, "; "))
		}
	}
	if len(cat.Platforms) > 0 {
		b.WriteString("\n## Partner platforms\n\n| Platform | What it is |\n| --- | --- |\n")
		for _, pl := range cat.Platforms {
			fmt.Fprintf(&b, "| [%s](platforms/%s.md) | %s |\n", mdText(pl.Name), pl.ID, mdText(pl.Description))
		}
	}
	return b.String()
}

func appCard(a *manifest.App, meta Meta) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n%s\n\n%s", mdText(a.Name), mdText(a.Description), generatedLine(meta))
	rows := [][2]string{
		{"Vendor", mdText(a.Vendor.Name)},
		{"Categories", mdText(strings.Join(a.Categories, ", "))},
		{"Vendor docs", "<" + a.DocsURL + ">"},
		{"Default provider", code(a.DefaultProvider)},
		{"Lifecycle", lifecycle(a.Lifecycle.Status, a.Lifecycle.SunsetAt, a.Lifecycle.ReplacedBy)},
	}
	writeTable(&b, rows)
	for _, p := range a.ProviderOrder() {
		providerSection(&b, a, p)
	}
	writeSources(&b, "## Sources", a.Sources)
	return b.String()
}

func providerSection(b *strings.Builder, a *manifest.App, p *manifest.Provider) {
	title := "## Provider " + code(p.ID)
	if p.ID == a.DefaultProvider {
		title += " (default)"
	}
	b.WriteString("\n" + title + "\n")
	rows := [][2]string{
		{"Kind", kindText(p)},
		{"Publisher", p.Publisher},
		{"Vendor status", p.VendorStatus.Label},
		{"Tier", p.Quality.Tier},
		{"Catalog ref", code(catalogRef(p))},
		{"Lifecycle", lifecycle(p.Lifecycle.Status, p.Lifecycle.SunsetAt, p.Lifecycle.ReplacedBy)},
	}
	if p.Transport.Kind == "http" {
		rows = append(rows, [2]string{"Endpoint", code(p.Transport.URL)})
		rows = append(rows, urlVariableRows(p.Transport.URLVariables)...)
	} else {
		rows = append(rows, [2]string{"Command", code(strings.Join(append([]string{p.Transport.Command}, p.Transport.Args...), " "))})
		if names := sortedKeys(p.Transport.Env); len(names) > 0 {
			rows = append(rows, [2]string{"Environment", codeList(names)})
		}
	}
	rows = append(rows, [2]string{"Auth", authText(p)})
	if o := p.Auth.OAuth2; o != nil && len(o.Scopes) > 0 {
		rows = append(rows, [2]string{"Scopes", codeList(o.Scopes)})
	}
	if ca := p.Auth.ClientApproval; ca.Pending() {
		rows = append(rows, [2]string{"Vendor approval", "Needs vendor approval: " + mdText(ca.Program) + " (<" + ca.URL + ">)"})
	}
	rows = append(rows,
		[2]string{"Account modes", mdText(strings.Join(p.AccountModes, ", "))},
		[2]string{"Default tool posture", p.Tools.DefaultPosture},
		[2]string{"Vendor pricing", strings.ReplaceAll(p.Pricing.Model, "_", " ")},
	)
	writeTable(b, rows)
	toolsTable(b, p)
	writeSources(b, "### Sources", p.Sources)
}

// urlVariableRows says what each of an endpoint's URL variables admits, in
// name order: its description, pattern, default and who sets it.
func urlVariableRows(vars map[string]manifest.URLVariable) [][2]string {
	names := make([]string, 0, len(vars))
	for name := range vars {
		names = append(names, name)
	}
	slices.Sort(names)
	rows := make([][2]string, 0, len(names))
	for _, name := range names {
		v := vars[name]
		def := "no default"
		if v.Default != "" {
			def = "default " + code(v.Default)
		}
		setBy := "set by the org"
		if v.Scope == "user" {
			setBy = "set by each user"
		}
		desc := strings.TrimRight(mdText(v.Description), ".")
		rows = append(rows, [2]string{"URL variable " + code(name),
			fmt.Sprintf("%s. Pattern %s; %s; %s", desc, code(v.Pattern), def, setBy)})
	}
	return rows
}

// genericToolLabel marks a generic tool's row: it takes
// its operation as an argument, so a per-tool policy sees only the verb.
const genericToolLabel = "Generic tool: per-tool policy sees only the verb"

func toolsTable(b *strings.Builder, p *manifest.Provider) {
	tools := p.AllTools()
	b.WriteString("\n### Tools\n\n")
	if len(tools) == 0 {
		b.WriteString("The catalog lists no tools for this provider; they are read from the server when it is connected.\n")
		return
	}
	b.WriteString("| Tool | What it does | Read-only | Destructive | Posture |\n| --- | --- | --- | --- | --- |\n")
	for _, t := range tools {
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n", code(t.Name), toolText(t),
			yesNo(t.Annotations.ReadOnlyHint), yesNo(t.Annotations.DestructiveHint), t.EffectivePosture(p.Tools.DefaultPosture))
	}
}

// toolText is a tool's "What it does" cell: its description, after the
// generic label and the arguments that carry the operation when it is
// generic.
func toolText(t manifest.Tool) string {
	if !t.Generic {
		return mdText(t.Description)
	}
	label := genericToolLabel
	if len(t.GenericArguments) > 0 {
		args := make([]string, len(t.GenericArguments))
		for i, a := range t.GenericArguments {
			args[i] = code(a)
		}
		label += "; the operation is in " + strings.Join(args, ", ")
	}
	return label + ". " + mdText(t.Description)
}

func platformCard(pl *manifest.Platform, meta Meta) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n%s\n\n%s", mdText(pl.Name), mdText(pl.Description), generatedLine(meta))
	rows := [][2]string{
		{"Connect modes", mdText(strings.Join(pl.Connect.Modes, ", "))},
		{"URL pattern", code(pl.Connect.URLPattern)},
		{"Account", pl.Account},
		{"Tool mode", pl.ToolMode},
		{"Self-hostable", yesNo(pl.SelfHostable)},
		{"Terms", fmt.Sprintf("<%s> (checked %s)", pl.TermsURL, pl.TermsCheckedAt)},
	}
	if len(pl.MetaTools) > 0 {
		rows = append(rows, [2]string{"Discovery tools switched off", codeList(pl.MetaTools)})
	}
	writeTable(&b, rows)
	writeSources(&b, "## Sources", pl.Sources)
	return b.String()
}

func kindText(p *manifest.Provider) string {
	switch p.Kind {
	case manifest.KindVendorMCP:
		return "vendor_mcp: the vendor's remote MCP server"
	case manifest.KindREST:
		return "rest: FutureAGI's MCP server over the vendor's REST API (agentcc-connectors)"
	case manifest.KindPartner:
		if pa := p.Auth.Partner; pa != nil {
			return "partner: the " + code(pa.Platform) + " platform's server for this app"
		}
		return "partner: a partner platform's server"
	}
	return "vendor_local: the vendor's local stdio server"
}

func authText(p *manifest.Provider) string {
	switch p.Auth.Kind {
	case manifest.AuthOAuth2:
		if p.Auth.OAuth2 != nil && p.Auth.OAuth2.PKCE {
			return "OAuth 2, with PKCE"
		}
		return "OAuth 2"
	case manifest.AuthMCPOAuth:
		return "MCP OAuth, discovered from the server"
	case manifest.AuthAPIKey:
		var parts []string
		for _, part := range p.Auth.CredentialParts {
			kind := "a setting"
			switch {
			case part.Secret:
				kind = "secret"
			case part.Value != "":
				kind = "set by the catalog"
			}
			parts = append(parts, fmt.Sprintf("%s in %s (%s)", code(part.Name), part.In, kind))
		}
		if len(parts) == 0 {
			return "API key"
		}
		return "API key: " + strings.Join(parts, ", ")
	case manifest.AuthPartner:
		return "through the partner platform"
	case manifest.AuthLocalSetup:
		return "set up where the server runs"
	}
	return strings.ReplaceAll(p.Auth.Kind, "_", " ")
}

func lifecycle(status, sunsetAt, replacedBy string) string {
	s := status
	if sunsetAt != "" {
		s += ", sunset " + sunsetAt
	}
	if replacedBy != "" {
		s += ", replaced by " + code(replacedBy)
	}
	return s
}

func writeTable(b *strings.Builder, rows [][2]string) {
	b.WriteString("\n| | |\n| --- | --- |\n")
	for _, r := range rows {
		fmt.Fprintf(b, "| %s | %s |\n", r[0], r[1])
	}
}

func writeSources(b *strings.Builder, heading string, sources []manifest.Source) {
	if len(sources) == 0 {
		return
	}
	b.WriteString("\n" + heading + "\n\n")
	for _, s := range sources {
		fmt.Fprintf(b, "- %s: <%s> (read %s)\n", code(s.Fact), s.URL, s.FetchedAt)
	}
}

func count(n int, noun string) string {
	if n == 1 {
		return "1 " + noun
	}
	return fmt.Sprintf("%d %ss", n, noun)
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

// mdText escapes text for a Markdown table cell or paragraph: it renders as
// the text it is, on one line.
func mdText(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '\\', '`', '*', '_', '[', ']', '<', '>', '|', '#', '!', '~', '&':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '\n', '\r', '\t':
			b.WriteByte(' ')
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// code renders s as a code span whose fence is longer than any run of
// backticks in it; a | is escaped, as a table cell needs.
func code(s string) string {
	longest, run := 0, 0
	for _, r := range s {
		if r == '`' {
			run++
			longest = max(longest, run)
		} else {
			run = 0
		}
	}
	fence := strings.Repeat("`", longest+1)
	s = strings.NewReplacer("|", `\|`, "\n", " ", "\r", " ").Replace(s)
	if longest > 0 {
		return fence + " " + s + " " + fence
	}
	return fence + s + fence
}

func codeList(items []string) string {
	out := make([]string, len(items))
	for i, s := range items {
		out[i] = code(s)
	}
	return strings.Join(out, ", ")
}

func sortedKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	slices.Sort(out)
	return out
}
