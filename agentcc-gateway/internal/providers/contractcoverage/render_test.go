package contractcoverage

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"github.com/futureagi/agentcc-gateway/internal/providers/contracttest"
	"github.com/futureagi/agentcc-gateway/internal/providers/contractwatch"
)

// generatedNote heads both documents.
const generatedNote = "<!-- Generated by internal/providers/contractcoverage; do not edit. Regenerate with: go test ./internal/providers/contractcoverage/ -update -->\n"

// renderCoverage writes CONTRACT_COVERAGE.md.
func renderCoverage(g *grid, reg *contractwatch.Registry) []byte {
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	// Totals.
	var native, presets, relays, variants int
	for _, r := range g.Rows {
		switch {
		case r.Adapter == "speech":
			relays++
		case r.Key == "vertex@":
			variants++
		case strings.HasSuffix(r.Key, "@"):
			presets++
		default:
			native++
		}
	}
	implemented, covered := 0, 0
	byKind := map[string]int{}
	for _, r := range g.Rows {
		for _, ep := range g.Cols {
			ce := g.Cells[r.Key][ep]
			if ce == nil {
				continue
			}
			implemented++
			switch {
			case ce.Cases > 0:
				covered++
			case ce.Exempt != nil:
				byKind[ce.Exempt.Kind]++
			}
		}
	}
	recordedModels := 0
	for _, m := range g.Models {
		if m.Recorded {
			recordedModels++
		}
	}
	errorCases, recordable := 0, 0
	for _, c := range g.Cases {
		if c.Error {
			errorCases++
		}
		if c.Recordable {
			recordable++
		}
	}
	regCovered := 0
	for _, name := range reg.Names() {
		regCovered += len(reg.Providers[name].Covered())
	}

	w("# Provider contract coverage")
	w("")
	b.WriteString(generatedNote)
	w("")
	w("Every provider API the gateway parses, by provider key and endpoint, with the number of contract cases")
	w("that pin it. A provider key is a native adapter, an OpenAI-compatible preset served by the openai adapter")
	w("(`<preset>@`, whose fixtures are the openai suite's `<preset>@<model>` directories), Vertex AI (`vertex@`,")
	w("the gemini adapter's `vertex@<model>` directories) or a speech-relay vendor. An endpoint is a capability")
	w("interface in `internal/providers/provider.go` that the adapter, constructed through `providers.NewRegistry`,")
	w("implements (type assertion, not a hand list); its cases are the fixtures whose `case.json` names it (`chat`")
	w("when there is none), or for the speech relay the sessions under `speech/testdata/sessions/`.")
	w("")
	w("`TestCoverageGrid` fails when an implemented cell has neither a case nor an entry in")
	w("`internal/providers/contractcoverage/exemptions.json` with a reason, and when an exemption is stale; so")
	w("the covered and exempt counts below always add up to every implemented cell. The losses the cases pin are")
	w("listed in [KNOWN_GAPS.md](KNOWN_GAPS.md). That every model in the model-watch registry has fixtures is")
	w("checked by `TestRegistryMatchesFixtures` in `internal/providers/contractwatch`.")
	w("")
	w("## Totals")
	w("")
	w("| | |")
	w("|---|---|")
	w("| provider keys | %d: %d native adapters, %d OpenAI-compatible presets, Vertex AI, %d speech-relay vendors |", len(g.Rows), native, presets, relays)
	var exemptParts []string
	for _, k := range kindOrder {
		if byKind[k] > 0 {
			exemptParts = append(exemptParts, fmt.Sprintf("%d %s", byKind[k], kindTitles[k]))
		}
	}
	exempt := implemented - covered
	w("| implemented cells (provider key × endpoint) | %d: **%d with contract cases**, %d exempt |", implemented, covered, exempt)
	w("| exempt cells | %s |", strings.Join(exemptParts, "; "))
	w("| models | %d: %d recorded from the real API, %d synthetic (authored from the provider's reference) |", len(g.Models), recordedModels, len(g.Models)-recordedModels)
	w("| cases | %d: %d error cases; %d recordable, %d synthetic only (`recordable: false`, or a speech session) |", len(g.Cases), errorCases, recordable, len(g.Cases)-recordable)
	w("| model-watch registry | %d covered models in %d sections of `contractwatch/known_models.json` |", regCovered, len(reg.Providers))
	_ = variants
	w("")

	// The grid.
	w("## Grid")
	w("")
	legend := []string{"a number is the cell's contract cases", "`·` the adapter does not implement the endpoint"}
	for _, k := range kindOrder {
		legend = append(legend, fmt.Sprintf("`%s` exempt: %s", kindMarks[k], kindTitles[k]))
	}
	w("Legend: %s. Columns are described under \"Endpoints\" below.", strings.Join(legend, "; "))
	w("")
	// Columns no adapter implements are left out (see "Endpoints").
	var cols []string
	for _, ep := range g.Cols {
		for _, r := range g.Rows {
			if r.Impl[ep] {
				cols = append(cols, ep)
				break
			}
		}
	}
	header := []string{"provider key", "models", "cases", "errors"}
	align := []string{"---", "--:", "--:", "--:"}
	for _, ep := range cols {
		header = append(header, shortNames[ep])
		align = append(align, ":-:")
	}
	w("| %s |", strings.Join(header, " | "))
	w("|%s|", strings.Join(align, "|"))
	modelsPerRow := map[string]int{}
	for _, m := range g.Models {
		modelsPerRow[m.Row]++
	}
	colCases := map[string]int{}
	for _, r := range g.Rows {
		var cases, errs int
		cells := []string{}
		for _, ep := range cols {
			ce := g.Cells[r.Key][ep]
			switch {
			case ce == nil:
				cells = append(cells, "·")
			case ce.Cases > 0:
				cells = append(cells, fmt.Sprint(ce.Cases))
				cases += ce.Cases
				errs += ce.Errors
				colCases[ep] += ce.Cases
			case ce.Exempt != nil:
				cells = append(cells, "`"+kindMarks[ce.Exempt.Kind]+"`")
			default:
				cells = append(cells, "**?**")
			}
		}
		w("| `%s` | %d | %d | %d | %s |", r.Key, modelsPerRow[r.Key], cases, errs, strings.Join(cells, " | "))
	}
	total := []string{}
	for _, ep := range cols {
		total = append(total, fmt.Sprint(colCases[ep]))
	}
	w("| **all** | %d | %d | %d | %s |", len(g.Models), len(g.Cases), errorCases, strings.Join(total, " | "))
	w("")

	// Endpoints.
	w("## Endpoints")
	w("")
	implementedBy := map[string][]string{}
	for _, r := range g.Rows {
		for _, ep := range g.Cols {
			if r.Impl[ep] {
				implementedBy[ep] = append(implementedBy[ep], r.Key)
			}
		}
	}
	w("| column | endpoint (`case.json`) | capability interface | provider keys implementing it |")
	w("|---|---|---|--:|")
	for _, c := range capabilities {
		iface := "`" + c.Iface + "`"
		switch {
		case c.Iface == "":
			iface = "`nativeTextCompletionProvider` (declared by `internal/server`)"
		case c.Endpoints[0] == contracttest.EndpointListModels:
			iface = "`Provider` (`ListModels`)"
		case c.Endpoints[0] == contracttest.EndpointChat:
			iface = "`Provider` (`ChatCompletion`, `StreamChatCompletion`)"
		}
		for _, ep := range c.Endpoints {
			note := "`" + ep + "`"
			switch ep {
			case endpointSearch, endpointVideo, endpointRealtime:
				note = "none: no contract endpoint"
			case endpointSpeechRelay:
				note = "none: the speech sessions"
			}
			n := fmt.Sprint(len(implementedBy[ep]))
			if n == "0" {
				n = "none (not in the grid)"
			}
			w("| %s | %s | %s | %s |", shortNames[ep], note, iface, n)
		}
	}
	w("")

	// Exemptions.
	w("## Exemptions")
	w("")
	w("From `internal/providers/contractcoverage/exemptions.json`.")
	for _, k := range kindOrder {
		var lines []string
		for _, e := range exemptionsByKind(g, k) {
			lines = append(lines, fmt.Sprintf("| `%s` | %s | %s |", e.Provider, strings.Join(e.Endpoints, ", "), oneLine(e.Reason)))
		}
		if len(lines) == 0 {
			continue
		}
		w("")
		w("### %s%s", strings.ToUpper(kindTitles[k][:1]), kindTitles[k][1:])
		w("")
		w("| provider key | endpoints | reason |")
		w("|---|---|---|")
		for _, l := range lines {
			w("%s", l)
		}
	}
	return b.Bytes()
}

// exemptionsByKind returns the distinct exemptions of kind k that apply to
// some cell, sorted by provider key.
func exemptionsByKind(g *grid, k string) []*Exemption {
	seen := map[*Exemption]bool{}
	var out []*Exemption
	for _, r := range g.Rows {
		for _, ep := range g.Cols {
			ce := g.Cells[r.Key][ep]
			if ce != nil && ce.Exempt != nil && ce.Exempt.Kind == k && !seen[ce.Exempt] {
				seen[ce.Exempt] = true
				out = append(out, ce.Exempt)
			}
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].Provider < out[j].Provider })
	return out
}

// oneLine makes s safe for a Markdown table cell.
func oneLine(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", `\|`)
}
