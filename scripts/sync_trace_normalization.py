"""Generate Go's embedded copy of the Python normalization contract."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "futureagi/tracer/utils/normalization/profiles.json"
TARGET = ROOT / "fi-collector/pkg/normalization/profiles_data.go"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = SOURCE.read_text()
    json.loads(raw)
    if "`" in raw:
        raise ValueError("Contract must not contain Go raw-string delimiters")
    expected = (
        "// Code generated by scripts/sync_trace_normalization.py; DO NOT EDIT.\n"
        "package normalization\n\nconst profileJSON = `" + raw + "`\n"
    )
    if args.check:
        if TARGET.read_text() != expected:
            raise SystemExit(
                "Normalization contract is out of sync; run scripts/sync_trace_normalization.py"
            )
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(expected)


if __name__ == "__main__":
    main()
