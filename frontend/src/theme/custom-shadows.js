// Named shadows from the Future AGI Design System (ds-tokens.js). Cards are
// flat (border, no shadow); only menus, dialogs, drawers and toasts float. The
// coloured "glow" shadows are gone: hover changes the fill instead.
import { dsCustomShadows } from "./ds-tokens";

export function customShadows(mode) {
  return dsCustomShadows(mode);
}
