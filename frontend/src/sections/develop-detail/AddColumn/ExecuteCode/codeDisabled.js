// the capability contract: custom Python code is turned off. The server never runs user
// code (its executor's exec() stays commented out) and refuses every code
// preview, create, edit and re-run with this same message; the UI shows the
// reason instead of a door that could only fail. Existing values stay
// readable. Nothing here turns code back on.

export const CODE_COLUMNS_DISABLED_REASON =
  "Custom Python code is turned off. Existing values stay readable, but code cannot be tested, added, edited or re-run.";

// The conditional branch node type that runs custom code.
export const CODE_BRANCH_TYPE = "extract_code";

/** A column generated by custom Python code. */
export const isCodeColumn = (column) =>
  (column?.originType ?? column?.origin_type) === "python_code";

/**
 * True when a conditional column's branch list has a code branch: a branch
 * whose node config (`branch_node_config` from the server, `branchNodeConfig`
 * in the form) has `type === "extract_code"`. Text elsewhere never counts.
 */
export const conditionalConfigUsesCode = (branches) =>
  Array.isArray(branches) &&
  branches.some((branch) => {
    const node = branch?.branch_node_config ?? branch?.branchNodeConfig;
    return (
      node !== null &&
      typeof node === "object" &&
      node.type === CODE_BRANCH_TYPE
    );
  });
