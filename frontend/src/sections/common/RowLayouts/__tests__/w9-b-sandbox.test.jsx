// The renderer's window is the frame inside the wrapper document (review
// M1); jsdom doesn't load srcdoc, so the test puts that frame in by hand.
const rendererWin = (frame) => {
  const doc = frame.contentDocument;
  let inner = doc.querySelector("iframe");
  if (!inner) {
    inner = doc.createElement("iframe");
    doc.body.appendChild(inner);
  }
  return inner.contentWindow;
};

const COLS = [
  { id: "c1", name: "customer_message", section: "input", editable: true },
  { id: "c3", name: "expected_reply", section: "expected", editable: true },
  { id: "o1", name: "answer", section: "outputs", editable: false },
];

describe("sandboxDoc", () => {
  it("uses exactly the no-network CSP", () => {
    expect(RENDERER_CSP).toBe(
      "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; font-src data:; form-action 'none'; base-uri 'none'",
    );
    expect(RENDERER_SANDBOX).toBe("allow-scripts");
  });
  it("puts the CSP first, then the bootstrap, then the author's HTML", () => {
    const doc = buildSrcdoc('<p id="mine">hi</p>', { id: "r1" });
    const csp = doc.indexOf('http-equiv="Content-Security-Policy"');
    const boot = doc.indexOf("window.fa = fa");
    const mine = doc.indexOf('<p id="mine">');
    expect(csp).toBeGreaterThan(-1);
    expect(csp).toBeLessThan(doc.indexOf("<script>"));
    expect(boot).toBeGreaterThan(csp);
    expect(mine).toBeGreaterThan(boot);
    expect(doc).toContain("securitypolicyviolation");
  });
  it("embeds the row as JSON that can't close the script", () => {
    const s = scriptJson({ a: "</script><script>alert(1)</script>" });
    expect(s).not.toContain("</script>");
    expect(JSON.parse(s).a).toBe("</script><script>alert(1)</script>");
  });
});

describe("rendererBridge", () => {
  it("accepts messages only from its own frame and only known shapes", () => {
    const b = createBridge({ columns: COLS });
    const frame = {};
    expect(
      b.accept({ source: {}, data: { type: MSG.height, px: 300 } }, frame),
    ).toBeNull();
    expect(
      b.accept({ source: frame, data: { type: "fa:eval", code: "x" } }, frame),
    ).toBeNull();
    expect(b.accept({ source: frame, data: "fa:propose" }, frame)).toBeNull();
    expect(
      b.accept({ source: frame, data: { type: MSG.height, px: 99999 } }, frame),
    ).toEqual({
      type: MSG.height,
      px: 2000,
    });
    expect(
      parseMessage({
        type: MSG.csp,
        directive: "connect-src",
        blocked: "https://example.com/w9",
      }),
    ).toEqual({
      type: MSG.csp,
      directive: "connect-src",
      blocked: "https://example.com/w9",
    });
    expect(blockedLine("https://example.com/w9", "connect-src")).toBe(
      "Blocked: the renderer tried to reach https://example.com/w9 (renderers have no network).",
    );
  });
  it("checks the column and the rate limits", () => {
    let t = 0;
    const b = createBridge({ columns: COLS, now: () => t });
    expect(b.propose({ column: "foo", value: "x" })).toEqual({
      refused: "Refused: column “foo” doesn't exist.",
    });
    expect(b.propose({ column: "answer", value: "x" }).refused).toContain(
      "generated by a run",
    );
    expect(b.propose({ column: "expected_reply", value: "x" }).column.id).toBe(
      "c3",
    );
    t += PROPOSE_LIMITS.intervalMs - 1;
    expect(b.propose({ column: "expected_reply", value: "y" })).toEqual({
      refused: "Refused: one change every half second.",
    });
    for (let i = 1; i < PROPOSE_LIMITS.perSession; i += 1) {
      t += PROPOSE_LIMITS.intervalMs;
      expect(
        b.propose({ column: "expected_reply", value: i }).column,
      ).toBeTruthy();
    }
    t += PROPOSE_LIMITS.intervalMs;
    expect(
      b.propose({ column: "expected_reply", value: "z" }).refused,
    ).toContain(`${PROPOSE_LIMITS.perSession} changes per Row view`);
    expect(b.count()).toBe(PROPOSE_LIMITS.perSession);
  });
  it("fits the frame to its content up to the layout's max height", () => {
    const auto = parseMessage({ type: MSG.height, px: 900, auto: true });
    expect(auto).toEqual({ type: MSG.height, px: 900, auto: true });
    // Content-fit stops at the max height; fa.setHeight is taken as asked.
    expect(frameHeight(auto, 320)).toBe(320);
    expect(frameHeight({ ...auto, px: 180 }, 320)).toBe(180);
    const manual = parseMessage({ type: MSG.height, px: 900 });
    expect(manual).toEqual({ type: MSG.height, px: 900 });
    expect(frameHeight(manual, 320)).toBe(900);
    // No max height recorded: the content's height (within 40–2000).
    expect(frameHeight(auto, undefined)).toBe(900);
    // The bootstrap marks its own content-fit messages.
    expect(buildSrcdoc("<p>", null)).toContain("auto: true");
  });
  it("refuses with the row's own reason when changes are off", () => {
    const b = createBridge({
      columns: COLS,
      disabledReason: () => "Viewers can't change rows",
    });
    expect(b.propose({ column: "expected_reply", value: "x" })).toEqual({
      refused: "Refused: Viewers can't change rows.",
    });
  });
  it("builds a values-only row payload by column name", () => {
    const f = (name, value) => ({
      column: { id: name, name },
      value,
      cell: { cell_value: "x" },
    });
    const p = rowPayload(
      {
        input: [f("customer_message", "hi")],
        expected: [f("expected_reply", "hello")],
        metadata: [f("intent", "refund")],
        noRole: [f("ticket_id", "T-1")],
        outputs: [
          {
            column: { id: "o", name: "answer" },
            cell: { cell_value: "ok", value_infos: { secret: 1 } },
          },
        ],
      },
      { order: 11 },
      "r12",
    );
    expect(p).toEqual({
      id: "r12",
      number: 12,
      input: { customer_message: "hi" },
      expected: { expected_reply: "hello" },
      metadata: { intent: "refund" },
      other: { ticket_id: "T-1" },
      outputs: { answer: "ok" },
    });
  });
});

describe("SandboxedRenderer", () => {
  const base = {
    html: "<p>row</p>",
    height: 240,
    payload: {
      id: "r12",
      number: 12,
      input: {},
      expected: {},
      metadata: {},
      other: {},
      outputs: {},
    },
    columns: COLS,
    cells: { c3: { value: "old", original: "old" } },
    datasetId: "ds-sbx",
    layout: { id: "v1", name: "Refund review" },
  };
  it("renders a scripts-only sandbox with no same-origin and no referrer", () => {
    render(<SandboxedRenderer {...base} />);
    const frame = screen.getByTestId("layout-renderer-frame");
    expect(frame.getAttribute("sandbox")).toBe("allow-scripts");
    expect(frame.getAttribute("sandbox")).not.toContain("allow-same-origin");
    expect(frame.getAttribute("referrerpolicy")).toBe("no-referrer");
    expect(frame.getAttribute("srcdoc")).toContain(RENDERER_CSP);
  });
  it("fits its content and applies a new max height without reloading", () => {
    const { rerender } = render(<SandboxedRenderer {...base} />);
    const frame = screen.getByTestId("layout-renderer-frame");
    const send = (data, source = rendererWin(frame)) =>
      act(() => {
        window.dispatchEvent(new MessageEvent("message", { data, source }));
      });
    // The wrapper's own window is not the renderer: ignored.
    send({ type: MSG.height, px: 333, auto: true }, frame.contentWindow);
    expect(getComputedStyle(frame).height).not.toBe("333px");
    send({ type: MSG.height, px: 187, auto: true });
    expect(getComputedStyle(frame).height).toBe("187px");
    rerender(<SandboxedRenderer {...base} height={120} />);
    expect(getComputedStyle(frame).height).toBe("120px");
    // The author's fa.setHeight is taken as asked.
    send({ type: MSG.height, px: 400 });
    expect(getComputedStyle(frame).height).toBe("400px");
  });
  it("turns a proposal from its frame into one pending change; ignores others", () => {
    useChangeSetStore.setState({ sets: {} });
    render(<SandboxedRenderer {...base} />);
    const frame = screen.getByTestId("layout-renderer-frame");
    const send = (source, data) =>
      act(() => {
        window.dispatchEvent(new MessageEvent("message", { data, source }));
      });
    send(window, {
      type: MSG.propose,
      column: "expected_reply",
      value: "forged",
    });
    // Nor from the wrapper frame's window.
    send(frame.contentWindow, {
      type: MSG.propose,
      column: "expected_reply",
      value: "forged",
    });
    expect(useChangeSetStore.getState().getOps("ds-sbx")).toHaveLength(0);
    send(rendererWin(frame), {
      type: MSG.propose,
      column: "expected_reply",
      value: "fixed",
    });
    const ops = useChangeSetStore.getState().getOps("ds-sbx");
    expect(ops).toHaveLength(1);
    expect(ops[0]).toMatchObject({
      op: "update_cell",
      row_id: "r12",
      column_id: "c3",
      value: "fixed",
      source: { kind: "layout", layout_id: "v1", name: "Refund review" },
    });
    send(rendererWin(frame), { type: MSG.propose, column: "foo", value: "x" });
    send(rendererWin(frame), {
      type: MSG.csp,
      directive: "connect-src",
      blocked: "https://example.com/w9",
    });
    const lines = screen.getByTestId("layout-renderer-lines").textContent;
    expect(lines).toContain("Refused: column “foo” doesn't exist.");
    expect(lines).toContain(
      "Blocked: the renderer tried to reach https://example.com/w9",
    );
  });
  it("asks before running someone else's renderer, once", () => {
    const onTrust = vi.fn();
    const view = {
      id: "v9",
      mine: false,
      created_by: "Asha Rao",
      state: { layout: { renderer: { html: "<p>" } } },
    };
    render(
      <RendererSlot view={view} trusted={{}} onTrust={onTrust} {...base} />,
    );
    expect(screen.queryByTestId("layout-renderer-frame")).toBeNull();
    expect(screen.getByTestId("layout-renderer-consent").textContent).toContain(
      "This layout runs code written by Asha Rao. It has no network and can only propose changes that you save with a version.",
    );
    fireEvent.click(screen.getByTestId("layout-renderer-run"));
    expect(onTrust).toHaveBeenCalledWith("v9");
  });
});
