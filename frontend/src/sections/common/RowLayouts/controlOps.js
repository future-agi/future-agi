// Row layouts (W9-4, B3): a layout's write-back buttons as data. Pure.
//
//   controls: [{id, label, kind: "set_field" | "set_status" | "add_tag",
//               column_id?, value?, status?, reason?, tag?}]
//
// A kind runs only when the change-set has its op (`set_status` / `set_tags`
// come with W3 A) and the Customize panel can edit it (changeSetKinds.js).
// The rules mirror W3 A's own dialogs: archiving needs a reason
// (ArchiveRowsDialog) and a tag can't hold , ; or | (TagRowsDialog splits
// typed tags on them).

/** Change-set op the control kind needs (W3 A adds the last two). */
export const CONTROL_OP = Object.freeze({
  set_field: "update_cell",
  set_status: "set_status",
  add_tag: "set_tags",
});
export const CONTROL_KIND_LABEL = Object.freeze({
  set_field: "Set a field",
  set_status: "Set the row status",
  add_tag: "Add a tag",
});
/** The row status W3 A archives with, which needs a reason. */
export const ARCHIVED_STATUS = "archived";
const TAG_SEPARATORS = /[,;|]/;

const quote = (s) => `“${s}”`;
const trimmed = (v) => String(v ?? "").trim();

/** The control kinds this branch can apply: the op must exist. */
export function controlKinds(opTypes = []) {
  return Object.keys(CONTROL_OP).filter((k) => opTypes.includes(CONTROL_OP[k]));
}

/**
 * Sentences for the layout's buttons. `statuses` = the row status labels
 * (`{approved: "Approved", …}`); when given, a status must be one of them.
 */
export function validateControls(
  controls,
  columns = [],
  kinds = ["set_field"],
  statuses = null,
) {
  if (!Array.isArray(controls))
    return ["The buttons of this layout can't be read."];
  const out = [];
  const labels = new Set();
  controls.forEach((c) => {
    const label = trimmed(c?.label);
    if (!label) {
      out.push("Every button needs a label.");
      return;
    }
    const key = label.toLowerCase();
    if (labels.has(key)) out.push(`Two buttons are named ${quote(label)}.`);
    labels.add(key);
    const btn = `Button ${quote(label)}`;
    if (!kinds.includes(c.kind)) {
      out.push(
        `${btn} can't run here: this dataset can't apply ${quote(c.kind)} changes.`,
      );
      return;
    }
    if (c.kind === "set_field") {
      const col = columns.find((x) => x.id === c.column_id);
      if (!col) out.push(`${btn}: pick the column it sets.`);
      else if (!col.editable)
        out.push(
          `${btn}: ${quote(col.name)} is generated by a run and can't be set.`,
        );
      if (c.value == null) out.push(`${btn}: give the value it sets.`);
    }
    if (c.kind === "set_status") {
      const status = trimmed(c.status);
      if (!status) out.push(`${btn}: pick the status it sets.`);
      else if (statuses && !Object.hasOwn(statuses, status))
        out.push(`${btn}: ${quote(status)} isn't a row status.`);
      if (status === ARCHIVED_STATUS && !trimmed(c.reason))
        out.push(`${btn}: archiving needs a reason.`);
    }
    if (c.kind === "add_tag") {
      const tag = trimmed(c.tag);
      if (!tag) out.push(`${btn}: give the tag it adds.`);
      else if (TAG_SEPARATORS.test(tag))
        out.push(`${btn}: a tag can't contain , ; or |.`);
    }
  });
  return out;
}

/** A new button's fields for one kind (the panel's blank form). */
export function blankControl(kind, columns = []) {
  if (kind === "set_status") return { kind, status: "", reason: "" };
  if (kind === "add_tag") return { kind, tag: "" };
  return {
    kind: "set_field",
    column_id: columns.find((c) => c.editable)?.id ?? "",
    value: "",
  };
}

/** The saved control: its kind's fields only, text trimmed. */
export function cleanControl(id, form) {
  const base = { id, label: trimmed(form.label), kind: form.kind };
  if (form.kind === "set_status") {
    const reason = trimmed(form.reason);
    return {
      ...base,
      status: trimmed(form.status),
      ...(reason ? { reason } : {}),
    };
  }
  if (form.kind === "add_tag") return { ...base, tag: trimmed(form.tag) };
  return { ...base, column_id: form.column_id, value: form.value };
}

/** `Mark fixed · Set the row status Needs review (Expected is wrong)`. */
export function controlSummary(c, { colName = () => "?", statuses } = {}) {
  const head = `${c.label} · ${CONTROL_KIND_LABEL[c.kind] ?? c.kind}`;
  if (c.kind === "set_field")
    return `${head} ${colName(c.column_id)} = ${c.value}`;
  if (c.kind === "set_status")
    return `${head} ${statuses?.[c.status] ?? c.status}${c.reason ? ` (${c.reason})` : ""}`;
  if (c.kind === "add_tag") return `${head} ${c.tag}`;
  return head;
}

/**
 * Why the layout's buttons can't run on this row, or null.
 * @param {{viewer?: boolean, asOfVersion?: string|number|null,
 *   pendingDelete?: boolean}} ctx
 */
export function controlsDisabledReason({
  viewer,
  asOfVersion,
  pendingDelete,
} = {}) {
  if (viewer) return "Viewers can't change rows";
  if (asOfVersion != null && asOfVersion !== "")
    return `This is v${asOfVersion}, read-only`;
  if (pendingDelete) return "This row is deleted in the pending version";
  return null;
}

/**
 * The pending change one button adds on one row, and its toast text.
 * @param {object} control
 * @param {{rowId: string, rowLabel: string, columns: object[],
 *   original?: (columnId: string) => *, layout: {id: string, name: string},
 *   statusLabel?: object}} ctx
 * @returns {{op: object, toast: string} | {error: string}}
 */
export function controlOp(control, ctx) {
  const source = {
    kind: "layout",
    layout_id: ctx.layout.id,
    name: ctx.layout.name,
  };
  if (control.kind === "set_field") {
    const col = ctx.columns.find((c) => c.id === control.column_id);
    if (!col || !col.editable)
      return { error: `The column this button sets isn't in this dataset.` };
    return {
      op: {
        op: "update_cell",
        row_id: ctx.rowId,
        column_id: col.id,
        value: control.value,
        before: ctx.original ? ctx.original(col.id) : undefined,
        source,
      },
      toast: `${ctx.rowLabel} · ${col.name}: ${String(control.value)} · in pending changes`,
    };
  }
  if (control.kind === "set_status") {
    const label = ctx.statusLabel?.[control.status] ?? control.status;
    const reason = trimmed(control.reason);
    return {
      op: {
        op: "set_status",
        row_ids: [ctx.rowId],
        status: control.status,
        ...(reason ? { reason } : {}),
        source,
      },
      toast: `${ctx.rowLabel} · ${label}${reason ? `: ${reason}` : ""} · in pending changes`,
    };
  }
  if (control.kind === "add_tag") {
    const tag = trimmed(control.tag);
    return {
      op: {
        op: "set_tags",
        row_ids: [ctx.rowId],
        add: [tag],
        remove: [],
        source,
      },
      toast: `${ctx.rowLabel} · tag ${tag} · in pending changes`,
    };
  }
  return { error: `This dataset can't apply ${quote(control.kind)} changes.` };
}

let opSeq = 0;
/** An id for one op a layout adds, so Undo takes back exactly that op. */
export const layoutOpId = () => {
  opSeq += 1;
  return `layout_op_${opSeq}`;
};

/**
 * How to take back one press of a button (or one renderer proposal)
 * exactly: the op it added goes by its id, and a pending change it replaced
 * comes back. Null when it can't be taken back on its own (the row is a
 * pending new row, whose add_row took the change).
 * @param {object[]} before  the change-set's ops just before the op
 * @param {object} op        the op added, with its id
 * @returns {{revert: string|null, restore: object|null}|null}
 */
export function undoPlan(before = [], op) {
  const rowId = op.row_id ?? op.row_ids?.[0];
  if (before.some((o) => o.op === "add_row" && o.temp_id === rowId))
    return null;
  if (op.op === "update_cell") {
    // The change-set keeps one op per cell: an earlier pending edit of the
    // cell was replaced (same id), so putting it back is the undo.
    const prev = before.find(
      (o) =>
        o.op === "update_cell" &&
        o.row_id === op.row_id &&
        o.column_id === op.column_id,
    );
    return prev
      ? { revert: null, restore: prev }
      : { revert: op.id, restore: null };
  }
  if (op.op === "set_status") {
    // A row keeps its latest pending status: the one it had comes back.
    const prev = before.find(
      (o) => o.op === "set_status" && (o.row_ids ?? []).includes(rowId),
    );
    if (!prev) return { revert: op.id, restore: null };
    const { id: _id, at: _at, ...rest } = prev;
    return { revert: op.id, restore: { ...rest, row_ids: [rowId] } };
  }
  return { revert: op.id, restore: null };
}

/** Run an undoPlan on a change-set (useChangeSet's revert / addOp). */
export function runUndo(changeSet, plan) {
  if (!plan) return;
  if (plan.revert) changeSet.revert(plan.revert);
  if (plan.restore) changeSet.addOp(plan.restore);
}
