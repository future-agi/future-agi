// Row layouts (W9-4): the Row tab as a saved layout lays it out. Fields
// render through FieldCard + ValueViewer (the one renderer set) in the
// layout's view mode, in its order, in one or two columns; hidden fields
// fold into `Hidden fields (n)`; Edit is the default view's edit path.
// The Row-tab mount (bar, Customize, Copy) is RowLayoutTab.jsx.
import React, { useMemo, useState } from "react";
import PropTypes from "prop-types";
import { Box, ButtonBase, Stack, Typography } from "@mui/material";
import Iconify from "src/components/iconify";
import FieldCard from "src/sections/common/ValueViewer/FieldCard";
import ValueViewer from "src/sections/common/ValueViewer/ValueViewer";
import FieldEditor from "src/sections/develop-detail/DataTab/DatapointDrawerV2/FieldEditor";
import { CUSTOM_VIEW, splitSides } from "./layoutModel";
import { matchLayout, missingLine, valuesOf } from "./layoutMatch";

/** One field in its layout view mode (the user may still switch it here). */
const LayoutValue = ({ field, value }) => {
  const [view, setView] = useState(field.view);
  return (
    <ValueViewer
      value={value}
      dataType={field.column.data_type}
      view={view}
      onViewChange={setView}
      basePath={field.column.name}
      clampChars={0}
    />
  );
};
LayoutValue.propTypes = {
  field: PropTypes.object.isRequired,
  value: PropTypes.any,
};

const LayoutField = ({ field, cell, edit }) => {
  const id = field.column.id;
  const editing = edit?.editingId === id;
  const userColumn = cell?.editable;
  const [open, setOpen] = useState(!field.collapsed);
  return (
    <FieldCard
      name={field.label || field.column.name}
      role={field.column.role}
      dataType={field.column.data_type}
      originType={field.column.origin_type}
      value={cell?.value}
      editable={Boolean(userColumn && edit?.canEdit)}
      edited={cell?.edited}
      previous={cell?.edited ? cell.original : undefined}
      locked={userColumn ? false : "Generated by a run · re-run to change"}
      onEdit={() => edit.start(id)}
      onRevert={() => edit.revert(id)}
      expanded={open || editing}
      onToggleExpanded={() => setOpen((o) => !o)}
    >
      {editing ? (
        <FieldEditor
          dataType={field.column.data_type}
          value={cell?.value}
          applyRef={edit.applyRef}
          onCancel={edit.cancel}
          onApply={(v) => edit.apply(id, v)}
        />
      ) : (
        // Keyed by the view so a new layout's mode replaces the old one.
        <LayoutValue key={field.view} field={field} value={cell?.value} />
      )}
    </FieldCard>
  );
};
LayoutField.propTypes = {
  field: PropTypes.object.isRequired,
  cell: PropTypes.object,
  edit: PropTypes.object,
};

/**
 * @param {{spec: object, columns: object[], model: object, edit: object,
 *   renderer?: React.ReactNode, controls?: React.ReactNode}} props
 *   `columns` = layoutColumns(model); `renderer` replaces the first field
 *   set to Custom (later Custom fields are drawn by the same renderer).
 */
const RowLayoutView = ({ spec, columns, model, edit, renderer, controls }) => {
  const [showHidden, setShowHidden] = useState(false);
  const cells = useMemo(() => valuesOf(model), [model]);
  const { fields, unplaced, missing } = useMemo(
    () => matchLayout(spec, columns),
    [spec, columns],
  );
  const gone = missingLine(missing);
  const { left, right, hidden } = splitSides(spec, fields);
  const allHidden = [...hidden, ...unplaced];
  const firstCustom = fields.find((f) => !f.hidden && f.view === CUSTOM_VIEW);

  const render = (list) =>
    list.map((f) => {
      if (f.view === CUSTOM_VIEW) {
        if (f !== firstCustom || !renderer) return null;
        return (
          <Box key="renderer" data-testid="layout-renderer-slot">
            {renderer}
          </Box>
        );
      }
      return (
        <Box key={f.column.id} data-testid={`layout-field-${f.column.name}`}>
          <LayoutField field={f} cell={cells[f.column.id]} edit={edit} />
        </Box>
      );
    });

  // While a field is being edited the sides stack (left, then right), so
  // the editor gets the full width (it is cramped at half the Row view).
  // Both sides stay rendered: a right-side field keeps its editor.
  const editingShown = fields.some((f) => f.column.id === edit?.editingId);
  const twoSides = spec.columns === 2;
  const two = twoSides && !editingShown;
  return (
    <Stack gap={1.25} data-testid="row-layout-view">
      {controls}
      {gone && (
        <Typography
          typography="s3"
          color="text.secondary"
          data-testid="layout-missing"
        >
          {gone}
        </Typography>
      )}
      {!firstCustom && renderer ? (
        <Box data-testid="layout-renderer-slot">{renderer}</Box>
      ) : null}
      <Box
        sx={{
          display: "grid",
          gap: 1.25,
          gridTemplateColumns: two
            ? "minmax(0,1fr) minmax(0,1fr)"
            : "minmax(0,1fr)",
          alignItems: "start",
        }}
      >
        <Stack gap={1.25} data-testid="layout-side-left" sx={{ minWidth: 0 }}>
          {render(left)}
        </Stack>
        {twoSides && (
          <Stack
            gap={1.25}
            data-testid="layout-side-right"
            sx={{ minWidth: 0 }}
          >
            {render(right)}
          </Stack>
        )}
      </Box>
      {allHidden.length > 0 && (
        <Box>
          <ButtonBase
            onClick={() => setShowHidden((s) => !s)}
            aria-expanded={showHidden}
            data-testid="layout-hidden-toggle"
            sx={{
              gap: 0.5,
              px: 0.75,
              py: 0.25,
              borderRadius: 0.5,
              color: "text.secondary",
              typography: "s2",
              "&:hover": { bgcolor: "action.hover" },
            }}
          >
            <Iconify
              icon={
                showHidden ? "eva:chevron-down-fill" : "eva:chevron-right-fill"
              }
              width={16}
            />
            {`Hidden fields (${allHidden.length})`}
          </ButtonBase>
          {showHidden ? (
            <Stack gap={1.25} sx={{ mt: 1 }} data-testid="layout-hidden-list">
              {allHidden.map((f) => (
                <Box
                  key={f.column.id}
                  data-testid={`layout-field-${f.column.name}`}
                >
                  <LayoutField
                    field={{
                      ...f,
                      view: f.view === CUSTOM_VIEW ? "auto" : f.view,
                    }}
                    cell={cells[f.column.id]}
                    edit={edit}
                  />
                </Box>
              ))}
            </Stack>
          ) : (
            <Typography
              typography="s3"
              color="text.disabled"
              sx={{ display: "block", pl: 3 }}
              noWrap
            >
              {allHidden.map((f) => f.column.name).join(" · ")}
            </Typography>
          )}
        </Box>
      )}
    </Stack>
  );
};

RowLayoutView.propTypes = {
  spec: PropTypes.object.isRequired,
  columns: PropTypes.array.isRequired,
  model: PropTypes.object.isRequired,
  edit: PropTypes.object,
  renderer: PropTypes.node,
  controls: PropTypes.node,
};

export default RowLayoutView;
