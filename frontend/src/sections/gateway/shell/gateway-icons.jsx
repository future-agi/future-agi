export const GATEWAY_ICON_NAMES = Object.keys(GLYPHS);

export function gatewayIconSrc(name) {
  const glyph = GLYPHS[name];
  if (!glyph) throw new Error(`Unknown gateway icon: ${name}`);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${glyph}</svg>`;
  return `data:image/svg+xml;base64,${btoa(svg)}`;
}

export function GatewayIcon({ name, size = 16, sx = {}, ...other }) {
  return (
    <SvgColor
      src={gatewayIconSrc(name)}
      data-gateway-icon={name}
      sx={{ width: size, height: size, flexShrink: 0, ...sx }}
      {...other}
    />
  );
}

GatewayIcon.propTypes = {
  name: PropTypes.oneOf(GATEWAY_ICON_NAMES).isRequired,
  size: PropTypes.number,
  sx: PropTypes.object,
};

// The FA nav sizes and colours its icons through cloneElement(icon, { sx }),
// so a rail icon is a plain SvgColor element, as config-navigation's icon()
// helper makes for the Future AGI nav.
export function gatewayNavIcon(name) {
  return <SvgColor src={gatewayIconSrc(name)} data-gateway-icon={name} />;
}
