import fs from "node:fs";
import process from "node:process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import { collectOfflineIcons } from "./collect-offline-icons.mjs";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.resolve(process.argv[2] || root);
const collections = require("@iconify/json/collections.json");
const version = require("@iconify/json/package.json").version;
const expectedVersion = JSON.parse(
  fs.readFileSync(path.join(root, "package.json"), "utf8"),
).devDependencies["@iconify/json"];
if (version !== expectedVersion)
  throw new Error(
    `Icon data version drift: installed ${version}, expected ${expectedVersion}`,
  );
const mapping = require("./offline-icon-aliases.json");
const inventory = collectOfflineIcons(root);
const result = {};
const licences = {};
const missing = [];

// Resolve inherited dimensions and transformations, including alias-of-alias.
function iconData(collection, name, seen = new Set()) {
  if (seen.has(name)) throw new Error(`Cyclic alias ${name}`);
  if (collection.icons[name]) return collection.icons[name];
  const alias = collection.aliases?.[name];
  if (!alias) return null;
  const parent = iconData(collection, alias.parent, new Set([...seen, name]));
  if (!parent) return null;
  const props = { ...alias };
  delete props.parent;
  return {
    ...parent,
    ...props,
    rotate: ((parent.rotate || 0) + (alias.rotate || 0)) % 4,
    hFlip: !!parent.hFlip !== !!alias.hFlip,
    vFlip: !!parent.vFlip !== !!alias.vFlip,
  };
}
for (const name of inventory.names) {
  if (mapping.local[name]) {
    result[name] = mapping.local[name];
    continue;
  }
  const resolved =
    mapping.redistributionReplacements[name] || mapping.aliases[name] || name;
  const [prefix, key] = resolved.split(":");
  const collection = require(`@iconify/json/json/${prefix}.json`);
  const data = iconData(collection, key);
  if (!data) {
    missing.push({ name, resolved });
    continue;
  }
  result[name] = {
    width: collection.width || 16,
    height: collection.height || 16,
    ...data,
  };
  const info = collections[prefix];
  licences[prefix] = {
    name: info.name,
    author: info.author,
    license: info.license,
    source: `@iconify/json@${version}/json/${prefix}.json`,
    icons: [...(licences[prefix]?.icons || []), resolved],
  };
}
function write(relative, content) {
  const target = path.join(out, relative);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content);
}
const json = (v) => `${JSON.stringify(v, null, 2)}\n`;
write("src/components/iconify/offline-icons.json", json(result));
write("public/assets/licences/icons/sets.json", json(licences));
write("asset-inventory.json", json({ ...inventory, missing }));

const countrySource = fs.readFileSync(
  path.join(root, "src/components/agent-definitions/helper.jsx"),
  "utf8",
);
const flags = [];
for (const [, code] of countrySource.matchAll(
  /\/assets\/country-flags\/([a-z]{2})\.svg/g,
)) {
  const name = `circle-flags:${code}`;
  const data = result[name];
  if (!data || data.rotate || data.hFlip || data.vFlip)
    throw new Error(`Unsupported country asset ${name}`);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${data.width} ${data.height}">${data.body}</svg>\n`;
  write(`public/assets/country-flags/${code}.svg`, svg);
  flags.push({
    file: `${code}.svg`,
    icon: name,
    digest: `sha256:${createHash("sha256").update(svg).digest("hex")}`,
  });
}
write(
  "public/assets/country-flags/provenance.json",
  json({
    source: `@iconify/json@${version}/json/circle-flags.json`,
    licence:
      "MIT; see ../licences/icons/circle-flags.txt (notice acquisition gate must pass)",
    files: flags,
  }),
);

// Keep every shipped language subset, but emit only WOFF2 (all supported
// browsers support it). Fontsource's exact family/weight/unicode-range and
// font-display:swap declarations are preserved, not recreated by hand.
let css =
  "/* Generated by scripts/generate-offline-assets.mjs. SIL OFL 1.1. */\n";
for (const [family, weights] of [
  ["inter", [400]],
  ["ibm-plex-sans", [400, 500, 600, 700]],
]) {
  for (const weight of weights) {
    for (const style of family === "inter"
      ? ["normal"]
      : ["normal", "italic"]) {
      const file = `${weight}${style === "italic" ? "-italic" : ""}.css`;
      let faces = fs
        .readFileSync(require.resolve(`@fontsource/${family}/${file}`), "utf8")
        .replace(/, url\([^)]*\.woff\) format\('woff'\)/g, "");
      if (family === "inter") {
        // Static 600/700 cannot preserve the UI's 650 weight. Use the pinned
        // vendored variable release; retain Google's original normal-style axis.
        faces = faces
          .replaceAll("font-weight: 400;", "font-weight: 100 900;")
          .replace(/\.\/files\/inter-(.+?)-400-normal\.woff2/g, (_, subset) => {
            const name = `inter-${subset}-wght-normal.woff2`;
            write(
              `src/assets/fonts/${name}`,
              fs.readFileSync(path.join(root, "src/assets/fonts", name)),
            );
            return `./${name}`;
          })
          .replaceAll("format('woff2')", "format('woff2-variations')");
      } else {
        faces = faces.replaceAll(
          "url(./files/",
          `url(@fontsource/${family}/files/`,
        );
      }
      css += `${faces}\n`;
    }
  }
  write(
    `public/assets/licences/${family}-OFL.txt`,
    fs.readFileSync(require.resolve(`@fontsource/${family}/LICENSE`), "utf8"),
  );
}
write("src/assets/fonts/fonts.css", css);
console.log(
  json({
    icons: Object.keys(result).length,
    sets: Object.keys(licences).length,
    unresolved: inventory.unresolved,
    missing,
  }),
);
if (inventory.unresolved.length || missing.length) process.exitCode = 1;
