#!/bin/sh
# Trim an installed site-packages tree. Run it in the BUILDER stage, before the
# runtime stage copies site-packages: a file deleted in a later runtime layer
# still ships in the earlier one and saves nothing.
#
# futureagi/Dockerfile.oss runs it unless --build-arg SLIM_SITE_PACKAGES=0
# (the EE/cloud builds turn it off: their code may call googleapiclient for
# other APIs). Measured on the futureagi/future-agi v1.41 amd64 site-packages
# layer (1,343.5 MB of files / 370.7 MB gzip), file-level:
#   1. googleapiclient discovery documents  -105.1 MB
#   2. litellm proxy admin UI                -16.6 MB
#   3. package test suites                   -104.1 MB (incl. their .pyc)
#   4. *.pyi stubs                             -5.9 MB
#   5. .debug_* sections of extension modules -69.5 MB
#   total -301 MB unpacked, ~-63 MB gzip (debug data and JSON compress well).
# Every removal was checked against the OSS tree:
#   * no first-party module imports a `*.tests` package (git grep, any indent);
#     third-party `tests` subpackages that their own package imports are kept
#     (prune_test_dirs.py)
#   * googleapiclient build() is called for exactly two APIs, both with the
#     default static_discovery (reads discovery_cache/documents/<api>.<v>.json)
#   * litellm is used as a library; nothing starts litellm's proxy server
set -eu
SP=${1:-/usr/local/lib/python3.11/site-packages}
STRIP_SO=${STRIP_SO:-1}
HERE=$(dirname "$0")
before=$(du -sm "$SP" | cut -f1)

# 1. googleapiclient ships ~600 static discovery documents. Keep the two used:
#      accounts/services/gcp_procurement.py       ("cloudcommerceprocurement", "v1")
#      accounts/services/gcp_service_control.py   ("servicecontrol", "v1")
DOCS="$SP/googleapiclient/discovery_cache/documents"
if [ -d "$DOCS" ]; then
    find "$DOCS" -name '*.json' \
        ! -name 'cloudcommerceprocurement.v1.json' \
        ! -name 'servicecontrol.v1.json' -delete
fi

# 2. litellm's bundled proxy admin UI (static Next.js export).
rm -rf "$SP/litellm/proxy/_experimental/out"

# 3. Package test suites (pandas 35, scipy 31, numpy 15, sklearn 14 MB ...).
python3 "$HERE/prune_test_dirs.py" "$SP"

# 4. Type stubs: read by type checkers, never imported.
find "$SP" -type f -name '*.pyi' -delete

# 5. Debug sections of extension modules (zstandard alone carries 21.6 MB).
#    strip_so.py keeps a stripped file only if it still dlopen()s.
if [ "$STRIP_SO" = 1 ]; then
    python3 "$HERE/strip_so.py" "$SP"
fi

after=$(du -sm "$SP" | cut -f1)
echo "slim-site-packages: ${before} MB -> ${after} MB"
