def get_personas_by_language(agent_language, agent_type: Optional[str] = None):
    """
    Get the appropriate persona list based on agent definition language.

    Args:
        agent_language (str): Language code from agent definition (e.g., 'hi' for Hindi, 'en' for English)

    Returns:
        list: List of personas matching the language (defaults to ENGLISH_PERSONAS)
    """
    # Check if language is Hindi (case insensitive check for both code 'hi' and full name 'hindi')

    if agent_language and (
        agent_language.lower() == "hi" or agent_language.lower() == "hindi"
    ):
        if agent_type and agent_type == "text":
            return HINDI_PERSONAS_TEXT

        else:
            return HINDI_PERSONAS

    # Default to English personas for all other languages
    if agent_type and agent_type == "text":
        return ENGLISH_PERSONAS_TEXT

    return ENGLISH_PERSONAS


