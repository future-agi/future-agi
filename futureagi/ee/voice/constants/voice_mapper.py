def select_voice_id(persona_data, provider=ProviderChoices.LIVEKIT):
    """
    Select appropriate voice_id based on persona attributes using a scoring system.

    Uses these persona fields (all optional except gender):
    - gender (required): male, female, non-binary
    - location: India (uses Indian voices)
    - language: Hindi (uses Indian voices)
    - age_group: 18-25, 25-32, 32-40, 40-50, 50-60, 60+ (+3 points if matched)
    - personality: Friendly, Professional, Confident, etc. (+2 points if matched)
    - communication_style: Direct, Casual, Formal, etc. (+2 points if matched)
    - accent: American, British, Indian, etc. (+2 points if matched)

    Args:
        persona_data (dict or str): Persona data dict or JSON string
        provider (ProviderChoices): Voice infrastructure provider —
            LIVEKIT returns Cartesia UUIDs,
            VAPI returns 11Labs-compatible voice names.

    Returns:
        str: Selected voice_id (e.g., 'phillip', 'marissa', 'steve', etc.)
    """

    try:
        if not persona_data or not isinstance(persona_data, dict):
            return DEFAULT_VOICES.get("male", "phillip")

        # Get gender first as primary filter
        gender = persona_data.get("gender", "").lower()
        if gender not in ["male", "female"]:
            gender = "male"  # Default to male if gender is unclear

        # Check if location is India or language is Hindi - use Indian voices only
        location = persona_data.get("location", "").lower()
        language = persona_data.get("language", "").lower()
        accent = persona_data.get("accent", "").lower()

        # Cartesia UUIDs are only valid for LiveKit infrastructure.
        # VAPI uses 11Labs-style voice names (e.g. "marissa", "phillip").
        if provider != ProviderChoices.VAPI:
            with open(
                "/app/backend/simulate/data/voices_by_language_and_gender.json",
                "r",
                encoding="utf-8",
            ) as f:
                CARTESIA_VOICES = json.load(f)

            try:
                cartestia_language_key = get_language_key(
                    language, accent, gender, CARTESIA_VOICES
                )
            except Exception as e:
                traceback.print_exc()

            if cartestia_language_key:
                return cartestia_language_key

        # Start with voices matching the gender
        available_voices = VOICE_MAPPING["gender"].get(
            gender, VOICE_MAPPING["gender"]["male"]
        )

        # Filter by age group if specified
        age_group = persona_data.get("age_group", "").lower()
        if age_group in VOICE_MAPPING["age_group"]:
            age_voices = VOICE_MAPPING["age_group"][age_group]
            available_voices = [v for v in available_voices if v in age_voices]

        # Filter by personality if specified
        personality = persona_data.get("personality", "").lower()
        if personality in VOICE_MAPPING["personality"]:
            personality_voices = VOICE_MAPPING["personality"][personality]
            available_voices = [v for v in available_voices if v in personality_voices]

        # Filter by communication style if specified
        communication_style = persona_data.get("communication_style", "").lower()
        if communication_style in VOICE_MAPPING["communication_style"]:
            style_voices = VOICE_MAPPING["communication_style"][communication_style]
            available_voices = [v for v in available_voices if v in style_voices]

        # If no voices match all criteria, fall back to gender-based selection
        if not available_voices:
            available_voices = VOICE_MAPPING["gender"].get(
                gender, VOICE_MAPPING["gender"]["male"]
            )

        # Return a random matching voice (or default)
        return (
            random.choice(available_voices)
            if available_voices
            else DEFAULT_VOICES.get(gender, "phillip")
        )
    except Exception:
        # print("I am inside exception of select_voice_id")
        return DEFAULT_VOICES.get(gender, "phillip")


def select_voice_with_llm(persona_data):
    """
    Use LLM to select the most appropriate voice based on persona.
    Works with new persona field structure.

    Args:
        persona_data (dict or str): Persona data dict or JSON string

    Returns:
        str: Selected voice_id
    """
    if persona_data.get("gender", "").lower() == "male":
        return "phillip"
    else:
        return "marissa"
    if not persona_data or not isinstance(persona_data, dict):
        return DEFAULT_VOICES.get("male", "phillip")

    try:
        # Prepare the prompt for LLM
        persona_summary = f"""
        Persona Details:
        - Gender: {persona_data.get("gender", "unknown")}
        - Age Group: {persona_data.get("age_group", "unknown")}
        - Personality: {persona_data.get("personality", "unknown")}
        - Communication Style: {persona_data.get("communication_style", "unknown")}
        - Profession: {persona_data.get("profession", "unknown")}
        - Location: {persona_data.get("location", "unknown")}
        """

        voices_info = "\n".join(
            [
                f"- {voice['id']}: {voice['description']} ({voice['gender']})"
                for voice in AVAILABLE_VOICES
            ]
        )

        prompt = f"""
        Based on the following persona details, select the most appropriate voice from the available options.

        {persona_summary}

        Available Voices:
        {voices_info}

        Please select the voice_id that best matches this persona. Consider:
        1. Gender preference
        2. Age appropriateness
        3. Personality match
        4. Communication style alignment
        5. Professional context

        Respond with only the voice_id (e.g., "phillip" or "marissa").
        """
        llm = LLM(
            model_name="gpt-4o-mini",
            temperature=0.1,  # Lower temperature for more consistent, structured output
            provider="openai",
            api_key=None,
        )
        messages = [
            {
                "role": "system",
                "content": "You are a voice selection expert. Choose the most appropriate voice based on persona characteristics.",
            },
            {"role": "user", "content": prompt},
        ]
        response = llm.call_llm(messages, "openai")
        selected_voice = response.strip().strip('"').strip("'")

        # Validate the selected voice exists
        voice_ids = [voice["id"] for voice in AVAILABLE_VOICES]
        if selected_voice in voice_ids:
            return selected_voice
        else:
            # Fallback to rule-based selection if LLM returns invalid voice
            fallback_voice = select_voice_id(persona_data)
            # Double-check fallback is valid
            if fallback_voice in voice_ids:
                return fallback_voice
            else:
                # Ultimate fallback to gender-based default
                gender = persona_data.get("gender", "male").lower()
                return DEFAULT_VOICES.get(gender, "phillip")

    except Exception as e:
        # Fallback to rule-based selection if LLM call fails
        print(f"LLM voice selection failed: {e}")
        fallback_voice = select_voice_id(persona_data)
        # Double-check fallback is valid
        voice_ids = [voice["id"] for voice in AVAILABLE_VOICES]
        if fallback_voice in voice_ids:
            return fallback_voice
        else:
            # Ultimate fallback to gender-based default
            gender = (
                persona_data.get("gender", "male").lower() if persona_data else "male"
            )
            return DEFAULT_VOICES.get(gender, "phillip")


def validate_and_return_voice(voice_id, persona_data=None):
    """
    Validate that voice_id exists in available voices, return safe fallback if not.

    Args:
        voice_id (str): Voice ID to validate
        persona_data (dict): Optional persona data for fallback selection

    Returns:
        str: Valid voice_id
    """
    voice_ids = [voice["id"] for voice in AVAILABLE_VOICES]

    if voice_id in voice_ids:
        return voice_id

    # If invalid voice_id, use fallback
    if persona_data:
        fallback_voice = select_voice_id(persona_data)
        if fallback_voice in voice_ids:
            return fallback_voice

    # Ultimate fallback
    gender = persona_data.get("gender", "male").lower() if persona_data else "male"
    return DEFAULT_VOICES.get(gender, "phillip")


