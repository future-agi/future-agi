// Run inside the built local image with stdin (--input-type=module).
// Real Kafka + ClickHouse + Django; only the model response is scripted.
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {randomUUID} from 'node:crypto';
import {mkdtemp, rm} from 'node:fs/promises';
import {Kafka, logLevel} from 'kafkajs';
const {runDaemon} = await import((process.env.OMEGA_RUNTIME_ROOT || '/app/worker') + '/daemon.mjs');

const scope = JSON.parse(process.env.OMEGA_E2E_SCOPE);
const django = process.env.OMEGA_E2E_DJANGO_URL;
const secret = process.env.OMEGA_INTERNAL_API_SECRET;
if (!scope.project_id || !scope.organization_id || !django || !secret) throw new Error('Explicit isolated Django scope and test secret required');
const traceId = randomUUID();
const spanId = '1234567890abcdef';
const stamp = new Date(Date.now() - 120000).toISOString().replace('T', ' ').replace('Z', '');
const row = {project_id: scope.project_id, org_id: scope.organization_id, trace_id: traceId, id: spanId,
  parent_span_id: '', name: 'synthetic refund', input: 'Refund exactly 10', output: 'Refunded 5',
  start_time: stamp, end_time: stamp, created_at: stamp, updated_at: stamp, is_deleted: 0, _version: 1};
const inserted = await fetch('http://omega-integration-clickhouse:8123/', {method: 'POST',
  headers: {'X-ClickHouse-User': 'default', 'X-ClickHouse-Key': 'omega_local_fixture'},
  body: 'INSERT INTO default.spans FORMAT JSONEachRow\n' + JSON.stringify(row)});
if (!inserted.ok) throw new Error('Synthetic ClickHouse insert failed: ' + inserted.status);
await inserted.body.cancel();

let modelCalls = 0, firstPublication, finalReceipt;
const publicationBodies = [];
const control = new AbortController();
const deadline = setTimeout(() => control.abort(new Error('Cross-service test deadline')), 120000);
const server = createServer(async (request, response) => {
  try {
    let raw = '';
    for await (const chunk of request) {
      raw += chunk;
      if (Buffer.byteLength(raw) > 2 * 1024 * 1024) throw new Error('Fixture request too large');
    }
    if (request.url === '/v1/chat/completions') {
      modelCalls++;
      const body = JSON.parse(raw);
      const system = body.messages.find(message => message.role === 'system').content;
      const verifier = system.includes('Independently check');
      const toolReply = body.messages.find(message => message.role === 'tool');
      let message;
      if (!toolReply) message = {role: 'assistant', content: '', tool_calls: [{id: 'r' + modelCalls, type: 'function',
        function: {name: 'read_span', arguments: JSON.stringify({span_id: spanId, offset: 0, length: 4096})}}]};
      else {
        // Receipt ID is generated by the actual worker from actual CH bytes.
        const evidenceId = toolReply.content.match(/1234567890abcdef:\d+:\d+/)?.[0];
        assert.ok(evidenceId);
        const unknown = {status: 'unknown', span_id: null, evidence_ids: []};
        const assessment = {outcome: 'failure', requirement_checks: [{requirement_id: 'amount', requirement: 'Refund 10',
          status: 'violated', evidence_ids: [evidenceId]}], findings: [{finding_id: 'f1', kind: 'incorrect refund amount',
          statement: 'Refunded 5 instead of the requested 10', requirement_id: 'amount', recovery: 'not_recovered', evidence_ids: [evidenceId],
          attribution: {origin: {status: 'supported', span_id: spanId, evidence_ids: [evidenceId]}, decisive: unknown, symptom: unknown}}]};
        message = {role: 'assistant', content: JSON.stringify(verifier ? assessment : {
          action: 'finish', question: '', child_instructions: '', assessment})};
      }
      response.writeHead(200, {'Content-Type': 'application/json', 'x-agentcc-cost': '0.000100', 'x-agentcc-model-used': 'synthetic-gateway'});
      response.end(JSON.stringify({choices: [{message}], usage: {prompt_tokens: 100, completion_tokens: 50}}));
      return;
    }
    if (!request.url.startsWith('/tracer/internal/error-feed-v2/')) { response.writeHead(404); response.end(); return; }
    const upstream = await fetch(django.replace(/\/$/, '') + request.url, {method: request.method,
      headers: {'Content-Type': 'application/json', Authorization: 'Bearer ' + secret}, body: raw});
    const result = await upstream.text();
    if (request.url.endsWith('/reports/')) {
      publicationBodies.push(JSON.parse(raw));
      if (upstream.ok && !firstPublication) {
        firstPublication = JSON.parse(result);
        // Simulate losing the acknowledgement after Django committed.
        response.writeHead(503); response.end('fixture dropped acknowledgement'); return;
      }
      if (upstream.ok) { finalReceipt = JSON.parse(result); setTimeout(() => control.abort(), 100); }
      else process.stderr.write(JSON.stringify({stage: 'publication', status: upstream.status, error: result}) + '\n');
    }
    response.writeHead(upstream.status, {'Content-Type': 'application/json'}); response.end(result);
  } catch (error) {
    response.writeHead(500); response.end('fixture failed');
    control.abort(error);
  }
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const localUrl = 'http://127.0.0.1:' + server.address().port;
const scratch = await mkdtemp('/tmp/omega-cross-service-');
const kafka = new Kafka({clientId: 'omega-cross-service-producer', brokers: ['omega-integration-kafka:9092'], logLevel: logLevel.NOTHING});
const producer = kafka.producer();
try {
  await producer.connect();
  const event = {version: 1, event_id: randomUUID(), ...scope, event_kind: 'root_span_written',
    traces: [{trace_id: traceId, root_span_id: spanId, root_end_time: new Date(Date.now() - 120000).toISOString()}], emitted_at: new Date().toISOString()};
  const message = {key: scope.project_id, value: JSON.stringify(event)};
  await producer.send({topic: 'error-feed.trace-available.v1', messages: [message, message]});
  await runDaemon({...process.env,
    OMEGA_KAFKA_BROKERS: 'omega-integration-kafka:9092', OMEGA_KAFKA_GROUP: 'omega-cross-service-' + traceId,
    OMEGA_ENGINE_VERSION: 'omega-v1', OMEGA_REPORT_SPOOL: scratch + '/spool', OMEGA_SCRATCH_DIR: scratch,
    OMEGA_DJANGO_URL: localUrl, OMEGA_CONCURRENCY: '1',
    OMEGA_CLICKHOUSE_URL: 'http://omega-integration-clickhouse:8123', OMEGA_CLICKHOUSE_DATABASE: 'default',
    OMEGA_CLICKHOUSE_USERNAME: 'omega_reader', OMEGA_CLICKHOUSE_PASSWORD: 'omega_reader_fixture',
    AGENTCC_BASE_URL: localUrl + '/v1', AGENTCC_API_KEY: 'synthetic-gateway-key', OMEGA_MODEL_ID: 'synthetic-model'}, control.signal);
  assert.equal(firstPublication?.status, 'accepted');
  assert.equal(finalReceipt?.status, 'duplicate');
  assert.equal(firstPublication.report_id, finalReceipt.report_id);
  assert.equal(firstPublication.active_projection_updated, true);
  assert.equal(firstPublication.grouping_status, 'pending');
  assert.equal(firstPublication.occurrence_ids.length, 1);
  assert.equal(modelCalls, 4);
  assert.deepEqual(publicationBodies[0], publicationBodies[1]);
  assert.equal(publicationBodies[0].result.usage.cost_usd, 0.0004);
  assert.equal(publicationBodies[0].result.outcome, 'failure');
  process.stdout.write(JSON.stringify({status: 'passed', trace_id: traceId, report_id: firstPublication.report_id,
    real_services: ['Kafka', 'ClickHouse', 'Omega', 'Django', 'Postgres'], scripted: ['model/gateway response'],
    model_calls: modelCalls, fixture_reported_cost_usd: 0.0004, actual_inference_cost_usd: 0,
    duplicate_publication_did_not_repeat_inference: true, grouping_status: 'pending'}) + '\n');
} finally {
  clearTimeout(deadline); control.abort(); await producer.disconnect();
  server.closeAllConnections(); await new Promise(resolve => server.close(resolve));
  await rm(scratch, {recursive: true, force: true});
}
