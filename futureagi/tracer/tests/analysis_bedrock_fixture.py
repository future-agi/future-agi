"""Actual installed botocore request/parser stack; only HTTP/auth are synthetic."""

import io
import json
import sys
from types import SimpleNamespace
from unittest.mock import patch

import botocore.awsrequest
import botocore.parsers
import botocore.session
from botocore.httpsession import URLLib3Session

ERROR_WIRE = (
    b'{"message":"first","message":"second",'
    b'"finish_reason":"length","finish_reason":"stop",'
    b'"usage":{"input_tokens":1,"input_tokens":999},'
    b'"tool_calls":[{"function":{"name":"submit_summary",'
    b'"arguments":"{}","arguments":"{}"}}]}'
)


class InstalledBedrockHTTP:
    def __init__(self, case, *, status=200, error_at=1, error_wire=ERROR_WIRE):
        self.case, self.status, self.error_at = case, status, error_at
        self.cleanups = []
        case.addCleanup(self.close)
        self.error_wire = error_wire
        self.events, self.requests, self.error_field_reads = [], [], []
        self.sdk_error_decodes = 0
        self.strict_wires, self.success_wires = [], []
        self.observed_modules = set()
        parser_json = botocore.parsers.json
        proxy = SimpleNamespace(**vars(parser_json))

        def loads(raw, *args, **kwargs):
            self.events.append("sdk-json-decode")
            self.sdk_error_decodes += 1
            return parser_json.loads(raw, *args, **kwargs)

        proxy.loads = loads
        self.install(patch.object(botocore.parsers, "json", proxy))

    def close(self):
        while self.cleanups:
            self.cleanups.pop()()

    def install(self, patcher):
        patcher.start()
        self.cleanups.append(patcher.stop)

    def factory(self, service, options, response_factory):
        background_payloads = sys.modules[
            "ee.agenthub.traceerroragent.background_payloads"
        ]

        if id(background_payloads) not in self.observed_modules:
            self.observed_modules.add(id(background_payloads))
            proxy = SimpleNamespace(**vars(json))

            def loads(raw, *args, **kwargs):
                if "object_pairs_hook" in kwargs:
                    self.strict_wires.append(raw)
                    self.events.append("strict-original")
                return json.loads(raw, *args, **kwargs)

            proxy.loads = loads
            self.install(patch.object(background_payloads, "json", proxy))
        session = botocore.session.Session()
        session._config = {"profiles": {}}  # never load real AWS configuration
        client = session.create_client(
            service,
            region_name=options["region_name"],
            endpoint_url="https://offline.invalid",
            aws_access_key_id="offline-synthetic",
            aws_secret_access_key="offline-synthetic",
            config=options["config"],
        )
        self.cleanups.append(client.close)
        self.case.assertEqual(client.meta.config.retries["total_max_attempts"], 1)
        pending = {}
        observer = self

        class HTTP(URLLib3Session):
            def send(self, request):
                observer.requests.append(request)
                observer.events.append("http-response")
                # Exercise the existing worker response generator, NOT the SDK
                # response parser. The generated bytes pass through the real SDK.
                body = response_factory(**pending)["body"].read()
                failed = (
                    observer.status != 200
                    and len(observer.requests) == observer.error_at
                )
                if failed:
                    body = observer.error_wire
                else:
                    observer.success_wires.append(body.decode())
                status = observer.status if failed else 200

                class Raw(io.BytesIO):
                    def stream(self, amt=None, decode_content=False):
                        yield self.read()

                return botocore.awsrequest.AWSResponse(
                    request.url,
                    status,
                    {
                        "content-type": "application/json",
                        "content-length": str(len(body)),
                        "x-amzn-errortype": "ValidationException",
                    },
                    Raw(body),
                )

            def close(self):
                pass

        client._endpoint.http_session.close()
        client._endpoint.http_session = HTTP()
        invoke = client.invoke_model

        def invoke_model(**kwargs):
            pending.update(kwargs)
            try:
                return invoke(**kwargs)
            except Exception as exc:
                observer.events.append("sdk-exception")
                # Botocore already constructed its exception. From this boundary
                # on, even formatting it or reading its parsed response is a bug.
                cls = type(exc)
                getattribute = cls.__getattribute__

                def field(error, name):
                    if name in {"response", "args"}:
                        observer.error_field_reads.append(name)
                        raise AssertionError("application consumed SDK error fields")
                    return getattribute(error, name)

                def text(error):
                    observer.error_field_reads.append("message")
                    raise AssertionError("application formatted SDK error message")

                observer.install(patch.object(cls, "__getattribute__", field))
                observer.install(patch.object(cls, "__str__", text))
                raise

        client.invoke_model = invoke_model
        return client
