-- Whole dirty-bucket replacements, including tombstones for vanished keys.
-- Independent scopes MUST NOT share moments merely because stratum labels match.
-- Scope evidence includes missing/invalid units. Closed-stratum corrections and
-- support decisions are recomputed over the read window, not summed per bucket.
-- Scalar reads select moments/support only, not the serialized sketch states.
-- No TTL: explicit retirement and purge are serialized with publication in B07.
CREATE TABLE IF NOT EXISTS metric_bucket_totals
(
    org_id UUID,
    workspace_id UUID,
    project_id UUID,
    metric_id UUID,
    metric_version UInt32,
    bucket_start DateTime('UTC'),
    group_key String,
    scope_key String,
    stratum_key String,
    unit_count UInt64,
    valid_count UInt64,
    missing_count UInt64,
    invalid_count UInt64,
    population_missing UInt64,
    non_binary UInt64,
    sampled UInt64,
    known_sampled UInt64,
    census_disqualifiers UInt64,
    support_invalid UInt64,
    support_m UInt64,
    support_q UInt64,
    support_success UInt64,
    support_failure UInt64,
    nonempty_scope_count UInt64,
    weighted_n Float64,
    weighted_d Float64,
    sum_w Float64,
    sum_w2 Float64,
    p_min Float64,
    p_max Float64,
    population_min Float64,
    population_max Float64,
    support_p_min Float64,
    support_p_max Float64,
    b_yy Float64,
    b_xy Float64,
    b_xx Float64,
    c_yy Float64,
    c_xy Float64,
    c_xx Float64,
    support_n_min Float64,
    support_n_max Float64,
    support_d_min Float64,
    support_d_max Float64,
    support_n Float64,
    support_d Float64,
    support_nn Float64,
    support_nd Float64,
    support_abs_nd Float64,
    support_dd Float64,
    design_min String,
    design_max String,
    raw_design_min String,
    raw_design_max String,
    scope_min String,
    scope_max String,
    uniq_state AggregateFunction(uniqCombined64, String),
    quantile_state AggregateFunction(quantileTDigest, Float64),
    is_deleted UInt8,
    version UInt64,
    generation UInt64,
    attempt_id UUID,
    fencing_epoch UInt32,
    row_sequence UInt32
)
ENGINE = ReplacingMergeTree(version)
PARTITION BY toYYYYMM(bucket_start)
ORDER BY (org_id, project_id, metric_id, metric_version, bucket_start, group_key, scope_key, stratum_key, generation, attempt_id);

